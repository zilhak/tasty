for (const file of [...dsFiles, ...kitFiles]) {
  const src = readFileSync(file, "utf8");
  const rel = relative(vendor, file).replace(/\\/g, "/");
  for (const [, body] of src.matchAll(CSS_LITERAL)) sheets.push(`/* ${rel} */\n${body.trim()}`);
}
