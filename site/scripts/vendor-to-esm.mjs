  const src = readFileSync(join(vendor, "guidelines", name), "utf8")
    .replace(/href="(?:\.\.\/)+styles\.css"/g, 'href="../tokens.css"')
    // A card is served at `<base>/design/cards/<name>.html`; the icon sits at
    // `<base>/tasty-icon.png`. A relative path spells that under any base,
    // which a static file cannot do with `import.meta.env`.
    .replace(/(?:\.\.\/)+assets\/icons\/icon_256\.png/g, "../../tasty-icon.png")
    .replace(/<\/head>/, `${THEME_SYNC}\n</head>`);
  writeFileSync(join(cardsOut, name), src);
  cards++;
