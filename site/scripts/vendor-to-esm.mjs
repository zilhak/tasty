// The reference gallery is a second consumer of the same design system, and it
// is written the same way: each file pulls its vocabulary off a global and
// pushes what it defines back onto one. So it needs the same rewrite, over one
// more set of globals — plus one shape the kit does not have, the trailing
// `Gallery.mount(...)` that a browser used as the page's entry point. That
// becomes an exported page descriptor the site's route renders.
const outGallery = join(root, "src/gallery");
rmSync(outGallery, { recursive: true, force: true });
mkdirSync(outGallery, { recursive: true });

// `window.TastyDag` is published by two kit files; one barrel gives the gallery
// the single name it imports.
writeFileSync(
  join(outKit, "dag.js"),
  "// Generated by site/scripts/vendor-to-esm.mjs — the two kit files that publish window.TastyDag.\n" +
    'export * from "./overlays/dag_view.jsx";\nexport * from "./overlays/dag_surfaces.jsx";\n',
);

const GALLERY_MODULE = {
  Gallery: "./shell.jsx",
  OverlaysShared: "./overlays-shared.jsx",
  PresetEditor: "./preset_editor.jsx",
  TastyDesignSystem_41fd3f: "../ds/index.js",
  TastyDag: "../kit/dag.js",
};
const GLOBALS = Object.keys(GALLERY_MODULE).join("|");

/** End index of the balanced run that starts at `open` (a bracket), skipping
 *  strings, template literals and comments. */
const matchBracket = (src, open) => {
  const pairs = { "(": ")", "{": "}", "[": "]" };
  const stack = [pairs[src[open]]];
  for (let i = open + 1; i < src.length; i++) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === "\\") i++;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") { i = src.indexOf("\n", i); if (i === -1) break; continue; }
    if (c === "/" && src[i + 1] === "*") { i = src.indexOf("*/", i) + 1; continue; }
    if (pairs[c]) stack.push(pairs[c]);
    else if (c === stack[stack.length - 1]) { stack.pop(); if (!stack.length) return i; }
  }
  return -1;
};

/** Top-level comma split that also steps over strings and template literals. */
const splitArgs = (body) => {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c === '"' || c === "'" || c === "`") {
      for (i++; i < body.length && body[i] !== c; i++) if (body[i] === "\\") i++;
      continue;
    }
    if ("([{".includes(c)) depth++;
    else if (")]}".includes(c)) depth--;
    else if (c === "," && depth === 0) { out.push(body.slice(start, i)); start = i + 1; }
  }
  out.push(body.slice(start));
  return out.map((p) => p.trim()).filter(Boolean);
};

const G_PULL = new RegExp(
  String.raw`^[ \t]*const\s*\{([\s\S]*?)\}\s*=\s*window\.(${GLOBALS})\s*;[ \t]*$`,
  "gm",
);

let galleryCount = 0;
const galleryPages = [];
for (const name of readdirSync(join(vendor, "gallery")).sort()) {
  if (!name.endsWith(".jsx")) continue;
  let src = readFileSync(join(vendor, "gallery", name), "utf8");
  let needsBase = false;                         // whether the file links through the base
  const self = `./${name}`;
  const imports = new Map();
  const add = (global, spec) => {
    const mod = GALLERY_MODULE[global];
    if (mod === self) return;                    // a file does not import itself
    if (!imports.has(mod)) imports.set(mod, new Set());
    imports.get(mod).add(spec);
  };

  // `preset_editor.jsx` wraps its whole body in an IIFE so load order cannot
  // leak its locals. Modules already scope, and imports must be top level.
  src = src.replace(/^\(function \(\) \{$/m, "").replace(/^\}\)\(\);$/m, "");

  src = src.replace(G_PULL, (_all, body, global) => {
    for (const piece of splitArgs(body)) {
      const [key, alias] = piece.split(":").map((x) => x.trim());
      add(global, alias && alias !== key ? `${key} as ${alias}` : key);
    }
    return "";
  });

  // `window.PresetEditor && <window.PresetEditor.Section />` — a load-order
  // guard plus a late lookup. Modules resolve both, so import the symbol.
  src = src.replace(new RegExp(String.raw`window\.(${GLOBALS})\s*&&\s*`, "g"), "");
  src = src.replace(
    new RegExp(String.raw`<window\.(${GLOBALS})\.([A-Za-z_$][\w$]*)`, "g"),
    (_all, global, sym) => {
      add(global, `${sym} as ${global}_${sym}`);
      return `<${global}_${sym}`;
    },
  );
  src = src.replace(new RegExp(String.raw`</window\.(${GLOBALS})\.([A-Za-z_$][\w$]*)`, "g"),
    (_all, global, sym) => `</${global}_${sym}`);

  // `window.X = { … };` — what the file publishes. Anchored at the start of a
  // line: the same text appears in a header comment describing the file.
  const exported = [];
  for (const m of [...src.matchAll(new RegExp(String.raw`^[ \t]*window\.(?:${GLOBALS})\s*=\s*\{`, "gm"))].reverse()) {
    const open = m.index + m[0].length - 1;
    const close = matchBracket(src, open);
    const derived = [];
    for (const { name: key, expr } of entriesIn(src.slice(open + 1, close))) {
      // `Section: PresetEditorSection` renames — and the published name can be
      // one the file already imports, so it is exported under an alias rather
      // than bound again. `NAV_ITEM: {…}` publishes a literal and needs one.
      if (!expr) exported.push(key);
      else if (/^[A-Za-z_$][\w$]*$/.test(expr)) exported.push(`${expr} as ${key}`);
      else { derived.push(`const __pub_${key} = ${expr};`); exported.push(`__pub_${key} as ${key}`); }
    }
    src = src.slice(0, m.index) + derived.join("\n") + src.slice(src.indexOf(";", close) + 1);
  }

  // `Gallery.mount(active, nav, head, content)` was the page's entry point in a
  // browser. The site renders the page itself, so it becomes a description of
  // one rather than a call that mounts it.
  // Anchored at the start of a line so the sentence in shell.jsx's own header
  // comment ("then calls Gallery.mount(…)") is not mistaken for the call.
  const at = name === "shell.jsx" ? -1 : src.search(/^(?:window\.)?Gallery\.mount\(/m);
  if (at !== -1) {
    const open = src.indexOf("(", at);
    const close = matchBracket(src, open);
    const [active, nav, head, content] = splitArgs(src.slice(open + 1, close));
    src =
      src.slice(0, at) +
      `export const page = {\n  active: ${active},\n  nav: ${nav},\n  head: ${head},\n  content: ${content},\n};\n` +
      src.slice(src.indexOf(";", close) + 1);
  }

  src = src.replace(/(.)"(?:\.\.\/)+assets\/icons\/icon_256\.png"/g, (_all, before) => {
    needsBase = true;
    return before + baseHref(before, "tasty-icon.png");
  });

  // Specimen prose cross-links to sibling pages by the filename the gallery is
  // served under as a folder of documents. Here each is a route, under the
  // deployment base like every other link on the site.
  src = src.replace(/(.)"([a-z][a-z0-9-]*)\.html(#[^"]*)?"/g, (_all, before, key, hash) => {
    needsBase = true;
    const rest = `design/gallery/${key === "index" ? "" : `${key}/`}${hash || ""}`;
    return before + baseHref(before, rest);
  });

  const head = [`import React from "react";`];
  if (/\bReactDOM\./.test(src)) head.push(`import * as ReactDOM from "react-dom/client";`);
  if (needsBase) head.push(BASE_DECL);
  for (const [mod, specs] of [...imports].sort())
    head.push(`import { ${[...specs].join(", ")} } from "${mod}";`);
  // A gallery file publishes a hand-picked subset through its global; the rest
  // of its top-level components were reachable only because everything shared
  // one script scope. Modules do not, and the site's own chrome needs a few of
  // them (the shell's HowTo banner, its toggles), so every top-level component
  // is exported. Nothing imports the others, and Rollup drops what nothing
  // imports.
  const published = new Set(exported.map((e) => e.split(" as ").pop()));
  for (const [, fn] of src.matchAll(/^function ([A-Za-z_$][\w$]*)/gm))
    if (!published.has(fn)) { published.add(fn); exported.push(fn); }

  const tail = exported.length ? `\nexport { ${exported.join(", ")} };\n` : "";
  writeFileSync(join(outGallery, name), `${head.join("\n")}\n\n${src.trim()}\n${tail}`);
  if (at !== -1) galleryPages.push(name.replace(/\.jsx$/, ""));
  galleryCount++;
}

