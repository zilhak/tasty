/* Follows the page theme, unless the card pins one — the Latte swatches are
   about the light theme and must stay light in a dark page. Reads the same
   localStorage key the site writes, and the `storage` event fires in a frame
   when another document on the origin writes it, which is exactly the toggle. */
const THEME_SYNC = `<script>
(function () {
  var r = document.documentElement;
  if (r.hasAttribute("data-theme")) return;   // pinned by the card
  function apply(v) {
    if (v === "latte" || v === "light") r.setAttribute("data-theme", "latte");
    else if (v) r.removeAttribute("data-theme");
    else if (matchMedia("(prefers-color-scheme: light)").matches) r.setAttribute("data-theme", "latte");
  }
  try { apply(localStorage.getItem("tasty-theme")); } catch (e) {}
  addEventListener("storage", function (e) { if (e.key === "tasty-theme") apply(e.newValue); });
})();
</script>`;

let cards = 0;
