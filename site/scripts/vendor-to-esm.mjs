/**
 * Turns the vendored UI kit into ES modules the site can import.
 *
 * The kit is authored for a browser that loads every file with Babel standalone:
 * each file pulls what it needs off a global and pushes what it defines back onto
 * one. That is a module graph written in globals, and the shape is regular enough
 * to rewrite mechanically:
 *
 *   const { Tab, Kbd } = window.TastyDesignSystem_41fd3f;  ->  import { … } from ds
 *   const { Sidebar }  = window.TastyKit;                  ->  import { … } from kit
 *   window.TastyKit = Object.assign(window.TastyKit || {}, { A, B });  ->  export { A, B }
 *
 * `site/vendor/components/` is left alone — it already exports properly; it is
 * only copied so every import stays inside the Astro project root.
 *
 * Output (src/ds/, src/kit/) is derived and NOT committed. site/vendor/ is the
 * only source; regenerating is one `npm run prebuild`.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, copyFileSync } from "node:fs";
import { dirname, join, relative, resolve, posix } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const vendor = resolve(root, "vendor");
const dsSrc = join(vendor, "components");
const kitSrc = join(vendor, "ui_kits/terminal");
const outDs = join(root, "src/ds");
const outKit = join(root, "src/kit");

const walk = (dir, out = []) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith(".jsx")) out.push(p);
  }
  return out;
};

const exportsOf = (src) => {
  const names = new Set();
  for (const m of src.matchAll(/^export\s+(?:function|const|class)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm))
    for (const part of m[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop().trim();
      if (name) names.add(name);
    }
  return names;
};

/** Symbols a kit file publishes through `window.<Global> = Object.assign(...)`. */
const REGISTER = /window\.(?:TastyKit|TastyDag)\s*=\s*Object\.assign\(\s*window\.(?:TastyKit|TastyDag)\s*\|\|\s*\{\}\s*,\s*\{([\s\S]*?)\}\s*\)\s*;?/g;
/** Splits an object literal body on its top-level commas only. */
const splitTop = (body) => {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c === "(" || c === "[" || c === "{") depth++;
    else if (c === ")" || c === "]" || c === "}") depth--;
    else if (c === "," && depth === 0) { out.push(body.slice(start, i)); start = i + 1; }
  }
  out.push(body.slice(start));
  return out.map((p) => p.trim()).filter(Boolean);
};

/** Entries of a registration body: a bare name, or `name: <expression>`. */
const entriesIn = (body) =>
  splitTop(body).map((piece) => {
    const at = piece.indexOf(":");
    if (at === -1) return { name: piece.trim(), expr: null };
    return { name: piece.slice(0, at).trim(), expr: piece.slice(at + 1).trim() };
  });

const namesIn = (body) => entriesIn(body).map((e) => e.name);

/** Where the site is served from. `astro.config.mjs` `base` is the only place
 *  that path is written; Astro reports it without a trailing slash. */
const BASE_DECL = 'const BASE = `${import.meta.env.BASE_URL.replace(/\\/$/, "")}/`;';

/**
 * Replaces a string literal with one interpolating the base.
 *
 * A JSX attribute (`href="…"`) needs braces around the expression; the same
 * text as an object value (`href: "…"`) must not have them. The character
 * before the quote says which one this is.
 */
const baseHref = (before, rest) =>
  before === "=" ? `{\`\${BASE}${rest}\`}` : `\`\${BASE}${rest}\``;

/**
 * Marks a generated directory as a cache, per the CACHEDIR.TAG convention that
 * cargo uses for `target/`.
 *
 * These trees are copies of `site/vendor/`, rewritten. They are gitignored, so
 * they exist in a working tree and not in a fresh clone — and the repo's doc
 * guards walk the filesystem, not the index. Without a marker the same commit
 * gets judged differently depending on whether the generator has run, and the
 * verdict lands on comments this script did not write. The marker is the
 * property those guards already read (`tasty_doc_guards::is_build_cache_dir`).
 */
const markGenerated = (dir) => {
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "CACHEDIR.TAG"),
    "Signature: 8a477f597d28d172789f06886806bc55\n" +
      "# Generated by site/scripts/vendor-to-esm.mjs from site/vendor/. Do not edit.\n",
  );
};

rmSync(outDs, { recursive: true, force: true });
rmSync(outKit, { recursive: true, force: true });

// -------------------------------------------------------------------- ds
const dsFiles = walk(dsSrc);
const dsIndex = new Map();                       // symbol -> absolute output path
for (const file of dsFiles) {
  const rel = relative(dsSrc, file);
  const dest = join(outDs, rel);
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(file, dest);
  for (const name of exportsOf(readFileSync(file, "utf8"))) dsIndex.set(name, dest);
}
// Barrel, for the one kit file that takes the whole namespace.
const barrel = dsFiles
  .map((f) => `export * from "./${relative(dsSrc, f).replace(/\\/g, "/")}";`)
  .join("\n");
writeFileSync(join(outDs, "index.js"), `// Generated by site/scripts/vendor-to-esm.mjs\n${barrel}\n`);

// ------------------------------------------------------------------- kit
const kitFiles = walk(kitSrc);
const kitIndex = new Map();
for (const file of kitFiles) {
  const dest = join(outKit, relative(kitSrc, file));
  for (const m of readFileSync(file, "utf8").matchAll(REGISTER))
    for (const name of namesIn(m[1])) kitIndex.set(name, dest);
}

const specifier = (fromFile, toFile) => {
  let p = posix.relative(posix.dirname(fromFile.replace(/\\/g, "/")), toFile.replace(/\\/g, "/"));
  return p.startsWith(".") ? p : `./${p}`;
};

const PULL = /const\s*\{([\s\S]*?)\}\s*=\s*window\.(TastyKit|TastyDag|TastyDesignSystem_41fd3f)\s*;/g;
const WHOLE = /const\s+([A-Za-z_$][\w$]*)\s*=\s*window\.TastyDesignSystem_41fd3f\s*;/g;
const OPTIONAL = /window\.(TastyKit|TastyDag)\s*&&\s*window\.(?:TastyKit|TastyDag)\.([A-Za-z_$][\w$]*)/g;
const PROP = /window\.(TastyKit|TastyDag|TastyDesignSystem_41fd3f)\.([A-Za-z_$][\w$]*)/g;

let count = 0;
const unresolved = [];
for (const file of kitFiles) {
  const rel = relative(kitSrc, file).replace(/\\/g, "/");
  const dest = join(outKit, rel);
  let src = readFileSync(file, "utf8");
  let needsBase = false;                         // whether the file links through the base
  const imports = new Map();                     // specifier -> Set(spec)
  const add = (target, spec) => {
    const key = specifier(dest, target);
    if (!imports.has(key)) imports.set(key, new Set());
    imports.get(key).add(spec);
  };
  const lookup = (which, name) => (which === "TastyDesignSystem_41fd3f" ? dsIndex : kitIndex).get(name);

  src = src.replace(PULL, (_all, body, which) => {
    for (const piece of body.split(",").map((p) => p.trim()).filter(Boolean)) {
      const [name, alias] = piece.split(":").map((x) => x.trim());
      const target = lookup(which, name);
      if (!target) { unresolved.push(`${rel}: ${name} (${which})`); continue; }
      if (target === dest) continue;             // self-reference
      add(target, alias && alias !== name ? `${name} as ${alias}` : name);
    }
    return "";
  });

  // `const _TDS = window.TastyDesignSystem_41fd3f;` — the whole component library.
  src = src.replace(WHOLE, (_all, local) => {
    add(join(outDs, "index.js"), `* as ${local}`);
    return "";
  });

  // `window.TastyKit && window.TastyKit.X` — a late lookup the kit uses to avoid
  // load-order coupling. ES modules resolve that for us, so import X directly.
  src = src.replace(OPTIONAL, (all, which, name) => {
    const target = lookup(which, name);
    if (!target || target === dest) return all;
    add(target, name);
    return name;
  });

  src = src.replace(PROP, (all, which, name) => {
    const target = lookup(which, name);
    if (!target || target === dest) return all;
    add(target, name);
    return name;
  });

  const exported = new Set();
  src = src.replace(REGISTER, (_all, body) => {
    const derived = [];
    for (const { name, expr } of entriesIn(body)) {
      exported.add(name);
      // `pluginAttentionCount: <expr>` publishes a computed value, not a symbol.
      if (expr) derived.push(`const ${name} = ${expr};`);
    }
    return derived.join("\n");
  });

  // The kit points at the app icon with a path relative to its own preview
  // directory, which is not where the site serves it from. Every depth spells
  // the same file, so they all resolve to the one copied into `public/` below —
  // through the deployment base, which is written only in `astro.config.mjs`.
  src = src.replace(/(.)"(?:\.\.\/)+assets\/icons\/icon_256\.png"/g, (_all, before) => {
    needsBase = true;
    return before + baseHref(before, "tasty-icon.png");
  });

  // The kit's own preview bootstrap must not run when the file is imported.
  src = src.replace(/^\s*ReactDOM\.createRoot\([\s\S]*?\);\s*$/gm, (m) => {
    const top = m.match(/render\(\s*<([A-Za-z_$][\w$]*)/);
    if (top) exported.add(top[1]);
    return "";
  });

  const head = [`import React from "react";`];
  if (needsBase) head.push(BASE_DECL);
  for (const [mod, specs] of [...imports].sort()) {
    const list = [...specs];
    const ns = list.find((s) => s.startsWith("* as "));
    if (ns) head.push(`import ${ns} from "${mod}";`);
    const named = list.filter((s) => !s.startsWith("* as "));
    if (named.length) head.push(`import { ${named.join(", ")} } from "${mod}";`);
  }
  const tail = exported.size ? `\nexport { ${[...exported].join(", ")} };\n` : "";
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, `${head.join("\n")}\n\n${src.trim()}\n${tail}`);
  count++;
}

