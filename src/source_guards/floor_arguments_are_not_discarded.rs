//! 하한을 **인자로 받아 놓고 버리는** 자리를 잡는다.
//!
//! R1072 추출은 순회의 뿌리·하한·술어를 인자로 올려서 판정기가 합성 트리에서 돌 수
//! 있게 만드는 리팩터다. 그 추출이 반쯤만 되면 겉보기에는 성공한다 — 시그니처는
//! 인자를 받는데 본문이 그 인자를 안 쓰고 모듈 상수를 다시 읽는 것이다. 그러면 합성
//! 트리를 넘겨도 정본 하한이 적용되고, **대체 가능해졌다는 주장만 남는다.**
//!
//! # 무엇을 재는가
//!
//! 하한을 인자로 받는 함수의 본문이, 같은 축의 **모듈 상수 이름**을 다시 부르는가.
//! 축은 둘이고 인자 타입으로 가른다.
//!
//! 1. 순회 하한 타입을 참조로 받는 인자 — 같은 타입의 모듈 상수를 본문이 부르면 위반.
//! 2. 이름에 하한을 담은 `usize` 인자 — 하한 접두를 가진 모듈 상수를 본문이 부르면 위반.
//!
//! 둘째 축은 타입만으로 안 갈린다(모든 수가 `usize` 다). 그래서 **이름 관례에 기댄다** —
//! 인자 이름과 상수 이름의 관례가 깨지면 이 축은 조용해진다. 첫째 축에는 그 약점이 없다.
//!
//! # 겉함수를 안 잡는 이유 — 명명 규칙이 아니라 모수의 정의다
//!
//! 이 리팩터의 정상 형태는 짝이다. 겉함수는 생산 트리의 값을 한 자리에 모으고(상수를
//! 읽는 것이 그 함수의 **일**이다), 속함수는 그 값을 전부 인자로 받아 대체 트리에서
//! 돈다. 겉함수도 "인자를 받으면서 상수를 읽는" 모양이라, 그 문장을 술어로 쓰면 정상
//! 형태가 전부 걸린다.
//!
//! 짝의 이름(`…_under` 접미)으로 가르자는 제안이 있었고 실측했다: 그 접미 짝은 이
//! 레포 전체에 서른 있는데 그중 스물넷이 이 리팩터와 무관한 자리다(설정 저장·스크롤백
//! 같은 곳의 `…_in` 형태). 사거리를 가드 시험으로 좁히면 판별력이 생기지만, 좁혀야만
//! 성립한다.
//!
//! 그래서 이름을 안 쓴다. **모수를 "그 축의 인자를 실제로 받는 함수" 로 정의하면**
//! 겉함수는 애초에 모수 밖이다 — 겉함수는 그 인자를 안 받기 때문이다. 명명 관례가
//! 바뀌어도 이 구분은 안 흔들린다.
//!
//! # 초록이 뜻하는 것
//!
//! **인자를 받는 함수가 그 축의 모듈 상수를 이름으로 부르지 않는다.** 그것뿐이다.
//!
//! 초록이 뜻하지 **않는** 것 넷:
//!
//! - **인자가 실제로 쓰인다는 것이 아니다.** 인자를 아예 안 읽는 형태는 여기서 안 본다 —
//!   그 자리는 rustc 가 이미 잡는다(쓰이지 않는 변수 경고). 채널이 있는 자리에 판정기를
//!   또 지으면 사본이 둘이 된다.
//! - **하한 값이 옳다는 것이 아니다.** 그 물음은 각 판정기 자신의 것이다.
//! - **셋째 축(스캔 뿌리)은 안 본다.** 뿌리도 인자로 올라간 자리가 있는데 그 축은 아직
//!   안 쟀다.
//! - **상수를 이름 말고 다른 길로 읽는 것은 안 본다.** 상수를 지역 변수에 담아 넘기면
//!   본문에 상수 이름이 남아 이 판정에 걸리지만, 다른 함수를 거쳐 들어오면 안 걸린다.
//!   그 한 단계를 따라가는 데 필요한 것은 이름 해소이고, 그것이 이 한계를 깨는 측정이다.
//!
//! # 이 자리에 이미 채널이 있는가 — 절반만 있다 (실측)
//!
//! 규칙을 쓰기 전에 이미 그것을 하는 것을 찾는 것이 순서다(R1042). 찾았고, **모수
//! 전체를 덮지는 않는다.**
//!
//! 추출과 함께 합성 트리 시험을 붙인 자리에서는 그 시험이 이 결함을 잡는다. 실측:
//! 문서 인용 판정기의 속함수가 인자 대신 정본 하한을 읽게 바꾸자, 그 파일의 대체 트리
//! 시험이 "순회가 2 개만 모았다(하한 300)" 로 죽었다 — 합성 트리의 크기가 정본 하한에
//! 못 미치기 때문이다. 그 자리는 채널이 둘이다.
//!
//! 그런데 모수 아홉 파일 중 **둘은 합성 트리 시험을 아예 안 갖는다.** 그중 하나(거절문
//! 판정기의 순회 헬퍼)에 같은 변이를 심었더니 그 타깃 자신도, 문서 가드 패키지 전부도
//! 초록이었고 **이 판정기만 빨갰다.** 즉 이 판정기가 덮는 것은 "추출은 했는데 대체
//! 트리 시험은 아직 없는" 구간이다.
//!
//! 그래서 이 판정기는 대체 트리 시험을 대신하지 않는다. 둘은 겹치는 구간이 있고, 서로
//! 못 보는 구간도 각각 있다 — 이쪽은 하한을 안 넘기는 형태를 못 보고, 저쪽은 시험이
//! 없는 파일을 못 본다.

//! # 이 축의 수를 셀 때 — 손으로 만든 주석 제거기를 쓰지 마라 (실측)
//!
//! 이 축(하한)에는 같은 이름 아래 서로 다른 술어로 잰 수가 여럿 돌아다녔다. 2026-09-08
//! 에 **레포 자신의 마스킹 판정기 하나로** 전부 다시 쟀고, 그 결과 물음이 몇 개인지가
//! 갈렸다. 재는 뿌리는 셋(본체 소스 · 크레이트 · 통합 시험)이다.
//!
//! 수마다 **어느 사본에서 셌는지**를 함께 적는다. 술어만으로는 부족하다 — 같은 술어가
//! 사본에 따라 다른 값을 낸다는 것이 바로 이 절의 내용이기 때문이다.
//!
//! | 물음 | 사본 | 값 |
//! |---|---|---|
//! | 하한 값을 **만드는 자리 전부**(이름 없는 인라인 포함) | 코드가 아닌 부분을 덮은 것 | 41 |
//! | 그중 하한 라이브러리 자신의 파일을 뺀 것 | 〃 | 35 |
//! | **이름 붙은 선언** | 〃 | 28 |
//! | 하한을 받는 순회 함수의 **호출 자리** | 〃 | 36 |
//! | 같은 함수의 **언급 자리** | **원문**(아무것도 안 덮음) | 37 |
//!
//! 뒤의 둘은 이름을 갈라 둔다. 한 이름으로 부르면 다음 사람이 어느 쪽을 잰 값인지 못
//! 안다. 차이 하나는 그 라이브러리 자신의 설명 주석에 있는 언급이다.
//!
//! **"타입 표기가 하한 타입인 선언" 과 "이름 붙은 선언" 은 다른 물음이 아니었다.** 두
//! 술어의 결과 집합이 완전히 같다(28, 차집합 양방향 0). 한때 그 둘이 24 와 28 로
//! 달랐는데, 그것은 술어 차가 아니라 **재는 도구의 결함**이었다.
//!
//! 원인이 이 레포에서 반복될 형태라 적어 둔다. 손으로 만든 주석 제거기는 **산문 속의
//! 경로 글로브**를 블록 주석의 시작으로 읽는다 — 디렉토리 구분 문자 뒤에 별표가 오는
//! 형태가 블록 주석 여는 형태와 같기 때문이다. 이 레포의 문서 주석은 그런 경로를 자주
//! 쓴다. 닫는 짝이 뒤에 없으면 **그 지점부터 파일 끝까지가 통째로 덮이고**, 아래에 있는
//! 선언이 전부 사라진다. 실측: 파일 둘에서 선언 넷이 그렇게 사라졌고, 지어낸 것은
//! 0 이었다 — **거짓 음성만 나오는 형태라 화면에서는 조용한 통과로 보인다.**
//!
//! 손해가 **술어마다 얼마인지**도 쟀다. 정본 판정기가 만든 사본과, 주석만 손으로 걷은
//! 사본의 차다(뿌리는 위와 같은 셋):
//!
//! - 값을 만드는 자리 전부 −5 · 라이브러리 자신을 뺀 것 −5
//! - 이름 붙은 선언 −4 · 타입 표기로 세는 선언 −4
//! - 순회 함수 언급 −6
//!
//! **차가 0 인 술어는 없다.** 삼킴이 술어의 모양이 아니라 **자리**로 일어나기 때문이다 —
//! 그 지점 아래에 있는 것은 무엇이든 사라진다. 그래서 "내 술어는 안전하다" 는 판단이
//! 설 자리가 없다.
//!
//! 실제로 손해가 난 파일은 다섯이고 삼킴이 시작된 자리는 전부 **산문 속의 경로 글로브**
//! 였다. 좌표(잰 날 2026-09-08):
//!
//! | 파일 | 잃은 수 | 삼킴이 시작된 곳 |
//! |---|---|---|
//! | `one_concept_one_word_on_the_user_facing_surface.rs` | 선언 3 · 언급 1 | 5 줄, 모듈 문서 주석 |
//! | `build_cache_markers_are_name_prunable.rs` | 값 1 · 언급 2 | 108 줄, 설명 문자열 |
//! | `guard_test_channels_stay_split.rs` | 선언 1 · 언급 1 | 3 줄, 모듈 문서 주석 |
//! | `floored_walk_consumers_do_not_renormalize.rs` | 언급 1 | 42 줄, 설명 문자열 |
//! | `workspace_declares_no_walk_crate.rs` | 언급 1 | 9 줄, 모듈 문서 주석 |
//!
//! (다섯 다 `crates/tasty-doc-guards/tests/` 아래다.)
//!
//! **고칠 것은 산문이 아니라 도구다.** 경로를 글로브로 적는 것은 이 레포의 정상적인
//! 서술 방식이고, 정본 판정기는 그것을 옳게 다룬다. 산문을 고치는 처방을 쓰면 문서를
//! 잘 쓸수록 세기가 나빠지는 관계가 그대로 남는다.
//!
//! 좌변을 **세 번 셌고 세 수를 다 남긴다.** 버린 수도 값이다 — 남기지 않으면 다음
//! 사람이 같은 검출기로 같은 수를 다시 내고 그것을 믿는다.
//!
//! | 술어 | 사본 | 값 | 쓸 수 있나 |
//! |---|---|---|---|
//! | 함수 **이름**에 덮기·걷기를 뜻하는 조각이 든 파일 | 덮은 것 | 57 | 못 쓴다 — 탭 띠·베어러 토큰 제거처럼 주석과 무관한 이름이 대부분이다 |
//! | 주석 표시를 **코드에서 문자열로 들고 다니는** 파일 | 덮은 것 | 32 | 쓴다 — 주석을 손으로 다루는 코드가 이 형태다 |
//! | 그중 **블록** 주석을 다루는 것 | 〃 | 2 | 쓴다 — 이 함정의 실제 좌변이다 |
//! | (버림) 산문 속에 블록 여는 형태가 있는 파일 | 원문과 덮은 것의 대조 | 82 | **못 쓴다** — 진짜 블록 주석까지 세는 검출기였다. 진짜 주석은 닫는 짝이 있어 삼키지 않는다 |
//!
//! 이것을 잡는 **판정기는 안 지었다.** 세 축으로 재고 내린 판단이다:
//!
//! - **좌변 0.** 커밋된 코드에서 블록 주석을 손으로 다루는 자리는 둘인데, 둘 다 여는
//!   형태를 **줄 첫머리에서만** 본다. 산문 속 글로브는 줄 가운데에 있어 애초에 안 걸린다
//!   (둘 다 읽고 확인했다). 이 결함이 살았던 곳은 **회차 중에 쓰고 버리는 측정 스크립트**
//!   이고, 그것은 판정기가 원리적으로 못 본다.
//! - **처방이 자리에 안 맞는다.** "공용 판정기를 써라" 는 규칙은 다른 물음에 답하는
//!   특수 목적 제거기들(YAML 주석 · 마크다운 코드펜스 · 터미널 이스케이프)에도 걸린다.
//!   그 자리에서는 그 처방이 틀렸다.
//! - **방향이 나쁘다.** 더 잡는 쪽으로 틀리고, 실재하지 않는 위반에 대한 처방이 되며,
//!   따르면 그 자리가 면제로 굳는다.
//!
//! 그래서 이 축을 세는 일은 손도구로 하지 않는다는 것을 **규칙이 아니라 기록**으로
//! 남긴다. 레포가 그 물음에 답하는 판정기를 이미 갖고 있고, 이 판정기도 그것을 부른다.
//!
//! # 이 함정의 사거리 — 넓지 않다 (실측)
//!
//! 위 발견이 어디까지 적용되는지를 같은 날 이 회차의 다른 좌변들에 대고 쟀다. 걸린
//! 것은 **0** 이었고, 이유가 둘로 갈린다.
//!
//! - **집행되는 수는 구조적으로 막혀 있다.** 래칫 값을 내는 셸 게이트들이 정본 판정기를
//!   불러서 센다. 손도구가 낄 자리가 없다.
//! - **손으로 센 수 중 재현 가능한 것들은 정본과 값이 같았다.**
//!
//! 그래서 노출은 **회차 중에 손으로 세어 커밋문이나 문서에 박는 수**에 한정된다. 처방도
//! 그만큼 좁다 — "손으로 세지 마라" 가 아니라 **"손으로 센 수에는 술어와 어느 사본에서
//! 셌는지를 함께 적어라"** 다.
//!
//! 마지막 조각이 이 감사에서 나왔다. 어떤 자리는 정본으로 센 값과 **아무것도 안 덮은
//! 원문**으로 센 값이 같다. 그러면 "판정기를 썼다" 와 "원문에서 셌다" 가 관측상 구분이
//! 안 된다 — **차가 0 인 것은 판정기를 썼다는 증거가 아니다.** 술어 옆에 사본을 적게
//! 하면 그 구분이 공짜로 생긴다.
//!
//! # 사본을 **고를 수 없는** 술어가 있다
//!
//! 위 처방에 한 줄이 더 붙는다. 리터럴의 **내용**을 묻는 술어는 원문에서만 정의된다 —
//! 정본 판정기가 리터럴 내용을 공백으로 덮으므로, 그런 술어는 덮은 사본에서 **원리적으로
//! 0** 이다. 실측으로 그런 자리를 봤다: 어떤 축이 원문에서 67 이고 덮은 사본에서 0 인데,
//! 그 0 은 실패가 아니라 정의다.
//!
//! 그러니 사본을 적을 때 **고른 것인지 강제된 것인지**도 갈라야 한다. 안 그러면 다음
//! 사람이 "왜 판정기를 안 썼나" 를 묻고, 그 물음에 답이 없다.
//!
//! 반대쪽 끝도 실측했다. **사본을 고를 수 있는데 그 선택이 값을 크게 움직이는** 축이
//! 있다 — 한 축은 원문에서 33 이고 코드에서 1 이다(나머지 32 가 주석·문자열 안의
//! 언급이다). 같은 감사의 다른 축은 원문 398 · 코드 385 로 거의 안 움직인다. **사본
//! 선택의 비용은 축마다 다르고, 미리 알 수 없다** — 그래서 값이 아니라 사본을 적는다.
//!
//! 그리고 애초에 **사본 물음이 없는** 수도 있다. 파일 목록에서 나오는 수가 그렇다 —
//! 위 `mod.rs` 의 판정기 수가 그 예다. 셋을 섞으면 빈칸의 뜻이 갈리지 않는다: 안 적은
//! 것 · 고를 수 없는 것 · 물을 것이 없는 것.
//!
//! # 스캔 뿌리 축 — 하한 스물여덟이 각각 어느 뿌리에서 세는가
//!
//! 잰 트리는 통합 회차의 사본이고, **사본은 원문이다.** 뿌리는 문자열 리터럴이라 덮은
//! 사본에서는 빈칸으로 나온다 — 이 조사의 첫 판이 뿌리를 전부 빈 괄호로 냈고, 그것이
//! 바로 위에 적은 "고를 수 없는 것" 의 자기 적용이었다. 뿌리를 묻는 물음은 사본을
//! 고를 수 없는 것이 아니라 **한쪽에서만 정의된다.**
//!
//! ## 첫 수 — 뿌리는 열 종이다
//!
//! | 뿌리 | 하한 수 |
//! |---|---|
//! | 레포 루트 자체 | 6 |
//! | 크레이트 디렉토리 | 5 |
//! | 워크플로 디렉토리 | 3 |
//! | 문서 디렉토리 · 소스 디렉토리 · 가이드 원본 · 스크립트 · 루트 시험 · 번역 파일 | 각 2 |
//! | 상태 저장 소스 디렉토리 | 1 |
//!
//! 스물여덟 중 **스물일곱**이 뿌리를 갖는다. 하나는 안 갖는다 — 순회 하한이 아니라
//! **다른 순회의 산출물 길이**에 대한 하한이라, "어느 뿌리에서 세나" 라는 물음이
//! 성립하지 않는다. 그리고 뿌리 종수 열에는 **없는 디렉토리 하나**가 안 들어 있다:
//! 계층 가드가 하한이 실제로 무는지 보려고 일부러 빈 자리를 도는 음성 대조인데, 그것은
//! 모수의 뿌리가 아니라 시험의 뿌리다.
//!
//! ## 둘째 — 같은 뿌리인데 모수가 다른 자리
//!
//! 하한이 둘 이상인 뿌리가 아홉이다. 그 아홉이 셋으로 갈린다.
//!
//! **(가) 정본을 공유하는 넷.** 루트 시험 타깃 · 크레이트 시험 타깃 · 소스 파일 ·
//! 문서 파일. 짝의 양쪽이 순회 모듈의 모수 상수를 그대로 참조한다 — 값이 한 자리에만
//! 있으니 **갈릴 수가 없다.** 레포는 이 물음의 답을 이미 갖고 있다.
//!
//! **(나) 같은 값을 손으로 두 번 쓴 넷.** 가이드 원본 · 스크립트 · 번역 파일 ·
//! 워크플로. 네 짝 모두 뿌리도 거르개도 같고 잰 값도 같은데, 정본을 안 거치고 각자
//! 적어 두었다. 아직 안 갈렸을 뿐이다.
//!
//! **(다) 이미 갈린 하나.** 레포 루트에서 문서를 세는 하한이 둘인데 값이 여덟 다르다.
//! 처음에는 거르개 차이로 읽었다 — 한쪽에만 빌드 산출물 디렉토리를 빼는 조건이 한 줄
//! 더 있다. **실측하니 그 한 줄은 아무것도 안 거른다**(두 사본 어디서도 차가 0 이다).
//! 빌드 캐시 판정이 디렉토리 **이름**이 아니라 그 안의 표지 파일을 보기 때문에, 그
//! 조건은 표지가 이미 잡은 것을 다시 잡는다. 그러면 여덟은 어디서 왔는가 — **잰
//! 트리다.** 여덟은 전부 이 회차에 다른 lane 들이 착지시킨 결정 기록이었고, 두 하한은
//! 같은 날 서로 다른 브랜치에서 재어졌다.
//!
//! ## 셋째 — 이 차는 어느 빈칸인가
//!
//! 위에서 나눈 세 빈칸이 여기서 처음으로 다 쓰인다.
//!
//! · **안 적은 것** — 갈린 하나가 이 칸이다. 하한 구조체에는 잰 **날짜** 칸이 있는데
//!   잰 **트리** 칸이 없다. 여덟 lane 이 같은 날 각자의 브랜치에서 재면 날짜는 같고
//!   값은 다르다. 순회 모듈의 모수 구조체에는 그 칸이 있다 — 같은 레포 안에서 같은
//!   물음에 답이 둘이고, 하한 쪽이 그 칸을 안 가졌다.
//! · **고를 수 없는 것** — 워크플로 뿌리의 셋 중 하나가 이 칸이다. 그 하한은 뿌리를
//!   호출자가 공급하도록 일부러 따로 세운 것이라, 생산 자리와 합성 트리 양쪽에서
//!   쓰인다. 뿌리 하나를 적으면 나머지 자리가 거짓이 된다.
//! · **물을 것이 없는 것** — 뿌리를 안 갖는 하나가 이 칸이다.
//!
//! ## 판정기 — 안 짓는다
//!
//! 좌변은 **넷**이다((나)의 네 짝). 처방도 선다 — 모수 정본에 상수를 세우고 양쪽이
//! 그것을 참조하면 되고, 레포가 이미 (가)의 넷에서 그 형태를 실행했다. 방향도 한쪽이다.
//! 그런데 그 넷을 고치려면 여덟 파일을 만져야 하고, **이 회차에 그 여덟은 내 것이
//! 아니다.** 좌변을 안 고친 채 판정기만 착지시키면 빨간 판정기가 선다.
//!
//! 그래서 안 짓는 이유가 판정의 성질이 아니라 **회차의 성질**이다. 그 대신 재진입
//! 조건이 저절로 못 박힌다 — **다음 회차에, 그 여덟 파일의 소유를 받아서 짓는다.**
//! 좌변이 두꺼워지기를 기다리는 것도, 채널이 사라지기를 기다리는 것도 아니다.
//!
//! ## 안 닫은 칸 — 하강 정책 축
//!
//! 이 조사에는 칸이 둘 남아 있었고 하나만 닫았다. 안 닫은 것은 **각 하한이 어떤 하강
//! 정책으로 내려가는가**다. 이유는 자료가 아니라 **순서**다: 하강 정책은 뿌리와 짝으로만
//! 뜻이 있어서, 뿌리가 안 확정된 채로 정책을 세면 같은 정책이 다른 모수를 뜻하는 자리를
//! 못 가른다. 뿌리 축을 닫고 나서야 그 물음이 잴 수 있는 것이 됐다. 실제로 위 (다)의
//! 답이 정책 쪽에서 나왔다 — 두 하한의 하강 정책이 **같았고**, 그래서 차가 거르개도
//! 정책도 아닌 트리라는 것이 갈렸다. 정책 축 자체는 다음 회차에 연다.
//!
//! # 이 조사가 판정기를 안 지은 두 자리 — 칸 이름과 재진입 조건
//!
//! 안 지은 자리는 칸 이름이 붙어야 다음 사람이 논거를 처음부터 다시 안 짓는다. 칸은
//! 「판정기를 안 짓는 데는 세 이유가 있고 좌변은 마지막이다」 의 것이다.
//!
//! ## 산문 속 경로 무늬를 주석 시작으로 읽은 자리 — 칸은 **판정문**과 **사본** 둘이다
//!
//! 손으로 만든 주석 제거기가 산문에 적힌 경로 무늬를 블록 주석의 여는 표지로 읽었고,
//! 닫는 표지가 없으니 파일 끝까지 지웠다. 거짓 음성만 낳는 형태라 조용한 통과로 보인다.
//!
//! · **사본** — 그 결함은 커밋되지 않는 조사용 스크립트에 살았다. 판정기가 읽는 코퍼스
//!   밖이라 좌변이 0 인 것이 아니라 **안 보이는 것**이다.
//! · **판정문** — 처방이 그 자리에 안 맞는다. 시킬 말은 "정본 제거기를 써라" 인데, 그
//!   자리는 한 번 쓰고 버리는 도구라 고칠 대상이 아니다.
//!
//! **재진입 조건이 있다 — 없다고 적으면 안 된다.** 사본 칸의 재진입은 코퍼스가 그
//! 자리를 담게 되는 것이고, 여기서는 **손으로 만든 제거기가 커밋되는 소스에 들어오는
//! 것**이다. 그것은 가설이 아니라 전례다: 같은 물음에 손으로 만든 판이 셋 있던 시기가
//! 있었고, 셸 게이트들이 그 셋을 정본 하나로 접으면서 지금 형태가 됐다. 들어오는 순간
//! 코퍼스 안이고, 그러면 판정문 칸의 처방도 같이 옳아진다 — 재사용될 도구는 고칠
//! 대상이다. 두 칸의 재진입 조건이 같은 하나인 것은 우연이 아니라, 한쪽이 다른 쪽의
//! 전제였기 때문이다.
//!
//! ## 인자를 아예 안 쓰는 강한 형태 — 칸은 **채널**이다
//!
//! 이 판정기는 하한을 인자로 받아 놓고 모듈 상수로 바꿔 읽는 **약한** 형태를 센다.
//! 인자를 아예 안 쓰는 강한 형태는 안 센다 — 컴파일러의 미사용 인자 경고가 이미 그
//! 자리에서 답을 낸다. 답이 이미 다른 데서 나오면 판정기를 겹쳐 짓지 않는다.
//!
//! **재진입 조건이 있다.** 채널 칸의 약점은 그 칸을 세운 결정 기록 자신이 적어 두었다 —
//! 채널이 사라지면 그 자리는 판정의 전제를 잃는데, 사라지는 것을 알아채는 계기가
//! 자동으로는 안 생긴다. 여기서 채널이 사라지는 길은 둘이고 **둘 다 셀 수 있다**:
//! 그 자리에 미사용 인자 억제가 붙거나, 인자 이름이 밑줄로 시작하는 것. 그러니 조건은
//! **하한을 인자로 받는 함수에 미사용 인자 억제나 밑줄 이름이 나타나면**이다. 이 회차에
//! 그 수를 재지는 않았다 — 조건을 적는 데 새 측정이 필요하지 않고, 안 잰 것을 잰 것처럼
//! 두지 않으려고 그 사실을 여기 적는다.
//!
//! # 하강 정책 축 — 그리고 뿌리 축에서 내가 「갈릴 수 없다」로 센 것의 정정
//!
//! 잰 트리는 회차 95 기점 `12bc0f4b2` 의 사본이고, 사본은 **원문**이다(뿌리와 마찬가지로 정책도
//! 열거형 이름이라 덮은 사본에서는 안 보인다).
//!
//! ## 첫 수 — 하강을 정하는 **방식**이 둘이고, 그 위에 값이 셋이다
//!
//! 파일 순회는 하강을 **인자**로 받는다 — 전부 내려가기 · 빌드 캐시를 건너뛰기 · 거기에
//! 점 디렉토리까지 건너뛰기. 디렉토리 순회에는 **그 인자가 없다.** 하강이 거르개 함수의
//! 반환값 안에 들어 있어서, 디렉토리마다 모을지 · 내려갈지를 따로 정한다.
//!
//! 그래서 "이 하한은 어떤 정책으로 내려가는가" 라는 물음은 스물일곱 자리에 **같은 형태로
//! 안 걸린다.** 스물다섯은 값 하나로 답이 되고, 둘은 답이 함수다. 뿌리 축에서 나눈 세
//! 빈칸으로는 그 둘이 「물을 것이 없는 것」이 아니다 — 하강은 분명히 일어난다. **답이
//! 하나가 아닌 것**이고, 이것이 그 셋에 안 들어가는 넷째 형태다.
//!
//! 값의 분포는 전부 내려가기 13 · 빌드 캐시만 건너뛰기 8 · 점 디렉토리까지 4 ·
//! 함수로 정하기 2 다.
//!
//! ## ★ 뿌리 축의 「갈릴 수 없다」를 정정한다
//!
//! 뿌리 축에서 나는 모수 정본을 공유하는 짝 넷을 **「값이 한 자리에만 있으니 갈릴 수가
//! 없다」**로 셌다. 그 문장은 틀리지 않았지만 **묻지 않은 것이 있었다.** 갈릴 수 없는
//! 것은 **값**이지 **순회**가 아니다.
//!
//! 정본을 공유하는 짝 넷의 뿌리와 정책을 겹쳐 보면:
//!
//! | 공유하는 정본 | 자리 | 뿌리 | 정책 |
//! |---|---|---|---|
//! | 루트 시험 타깃 | 3 | **2 종** | **2 종** |
//! | 문서 파일 | 2 | **2 종** | **2 종** |
//! | 크레이트 시험 타깃 | 2 | 1 종 | **2 종** |
//! | 소스 파일 | 2 | 1 종 | 1 종 |
//!
//! **넷 중 셋이 뿌리나 정책에서 갈린다.** 순회가 다르면 그 값은 둘 중 한쪽에서만 참인데,
//! 정본을 공유하니 그 사실이 **값으로 나타나지 않는다.** 정본화는 갈림을 막는 것이
//! 아니라 **갈림을 안 보이게 한다** — 값이 갈리는 것은 시끄럽고, 순회가 갈리는 것은
//! 조용하다. 그래서 정본을 공유할 자격은 값이 같다는 데서 오는 것이 아니라 **두 순회가
//! 같은 것을 센다는 데서** 온다. 그것을 따로 보이지 않으면 정본화가 결함을 가린다.
//!
//! ## 갈린 셋이 실제로 무엇인가
//!
//! · **크레이트 시험 타깃** — 뿌리도 min 도 정본도 같은 두 자리가 한쪽은 빌드 캐시를
//!   건너뛰고 한쪽은 **전부 내려간다.** 지금 이 트리에서 차는 0 이다. 그런데 **차가 0 인
//!   것은 정책이 같다는 증거가 아니다** — 그 뿌리 아래에 빌드 캐시가 없어서 0 이다.
//!   워크스페이스 밖으로 뺀 크레이트를 따로 빌드하면 그 아래에 캐시가 생기고, 그때
//!   전부 내려가는 쪽만 그 안을 훑는다. 결과는 거르개가 막는다(경로 깊이 조건이 캐시
//!   안쪽을 안 집는다) — 그러나 **훑는 비용은 안 막는다.** 디렉토리 순회의 셋째 값이
//!   그 위험을 doc 에 적어 두었다: 빌드 캐시를 찾는 순회가 캐시 내부를 훑으면 그 가드
//!   자신이 사고의 규모를 재현한다.
//! · **루트 시험 타깃** — 셋이 공유하는데 하나는 뿌리가 레포 루트고 둘은 루트 시험
//!   디렉토리다. 도달 경로가 다른 것이 곧 결함은 아니다. 결함인 것은 **같은지 다른지를
//!   묻는 자리가 없다**는 것이다.
//! · **문서 파일** — 둘이 뿌리도 정책도 다르다. 한쪽은 문서 디렉토리를 전부 내려가고,
//!   한쪽은 레포 루트를 돌면서 문서 디렉토리로 시작하는 것만 집는다. 뿌리 축에서 나는
//!   같은 위험(커밋 안 되는 로컬 폴더가 기계마다 다른 좌변을 낸다)에 대한 처방이 이
//!   자리마다 다르다고 적었다 — 레포 루트를 도는 쪽이 점 디렉토리를 **안** 건너뛴다.
//!   지금 안전한 이유는 정책이 아니라 거르개다. 여기서도 **정책이 할 일을 거르개가
//!   하고 있다.**
//!
//! ## 판정기 — 이 회차에도 안 짓는다. 칸은 **소유**다
//!
//! 좌변은 **3**(정본을 공유하면서 뿌리나 정책이 갈리는 짝)이다. 방향도 한쪽이다 —
//! 정본 공유가 늘면 좌변이 는다. 처방은 갈래가 둘이라(순회를 맞추거나 정본을 나누거나)
//! 판정기가 혼자 못 정하지만, 두 갈래에 공통인 것이 하나 있다: **두 순회가 같은 것을
//! 센다는 것을 보여라.** 그것은 시킬 수 있는 말이다.
//!
//! 막은 것은 이번에도 소유다. 좌변 3 이 사는 파일은 이 회차에 내 것이 아니고, 좌변을
//! 안 고친 채 판정기만 착지시키면 빨간 판정기가 선다. 회차 94 에서 이 자리에 여섯 칸
//! 어디에도 안 들어가는 **소유** 칸을 제안했는데, 같은 칸의 둘째 실례가 여기서 나왔다 —
//! 한 번은 우연이고 둘은 형태다.
//!
//! 재진입 조건은 값이다: **좌변 3 이 사는 파일의 소유를 받으면.** 그리고 이 축의 값과
//! 술어는 하한 구조체를 만지는 lane 이 그대로 쓸 수 있게 여기 적어 둔다 — 구조체도,
//! 갈린 셋이 사는 파일도, 이 회차에 나는 **한 줄도 안 만졌다.**
//!
//! # ★ 앞의 두 축이 센 모수가 틀렸다 — 하한은 스물일곱이 아니라 서른둘이다
//!
//! 뿌리 축과 정책 축은 둘 다 **이름 붙은 상수로 선언된** 하한만 셌다. 그런데 하한이
//! 그 형태로만 오지 않는다. 인용 줄 수를 재는 가드 하나는 뿌리·하한·실측을 **명부의
//! 행으로 적고, 행마다 하한을 함수로 만들어** 쓴다. 그렇게 만들어지는 하한이 **다섯**이다.
//!
//! 그래서 두 축의 표를 고친다. 뿌리 **종수는 그대로 열이다** — 다섯의 뿌리가 전부 이미
//! 센 열 안에 있다. 바뀌는 것은 자리 수다: 문서 · 소스 · 루트 시험 · 스크립트가 각각
//! 하나씩, 크레이트가 하나 늘어 스물일곱이 서른둘이 된다. 정책은 다섯 다 빌드 캐시만
//! 건너뛰는 값이라 그 칸이 여덟에서 열셋이 된다.
//!
//! **그리고 새 결함 후보가 하나 늘었다.** 문서 뿌리를 도는 자리가 이제 셋이고, 그중 둘이
//! 같은 것을 센다 — 경로가 문서 디렉토리로 시작하고 마크다운으로 끝나는 것. 값은 402 와
//! 386 이다. 차의 절반은 명부 쪽이 자기 파일을 빼기 때문이고, 나머지는 **잰 트리**다:
//! 한쪽은 모수 구조체를 참조해 어느 커밋에서 셌는지가 값에 붙어 있고, 명부 쪽은 날짜만
//! 적혀 있다. 뿌리 축에서 적은 그 병의 셋째 실례이고, 이번에는 **한쪽이 이미 나은 상태**라
//! 대조가 선명하다.
//!
//! # 강한 형태의 채널이 살아 있는가 — 0 을 세 갈래로 갈랐다
//!
//! 앞에서 이 판정기가 강한 형태(인자를 아예 안 쓰는 것)를 안 세는 이유를 채널로 적고,
//! 채널이 사라지는 길 둘(미사용 인자 억제 · 밑줄 이름)을 재진입 조건으로 걸었다. 이제
//! 쟀고, **둘 다 0 이다.** 그런데 그 0 은 세 갈래로 갈린다.
//!
//! · **대리 술어의 0.** 억제와 밑줄은 진짜 물음의 대리다. 진짜 물음은 "인자를 안 쓰는
//!   형태가 **조용히 남을 수 있는가**" 인데, 조용히 남는 길은 그 둘 말고도 있다. 경고를
//!   오류로 올리지 않는 타깃에서는 표지가 하나도 없이 경고만 나고 빌드는 산다. 그것은
//!   **빌드 설정의 성질이라 소스 문자열로 안 세어진다 — 못 쟀다.**
//! · **모수가 틀린 0.** 이 술어는 하한 **타입의 인자**만 본다. 명부에서 하한을 만드는
//!   자리는 인자가 숫자라 술어의 시야 밖이다. 거기서 인자를 안 쓰는 형태도 같은 병인데
//!   안 세어졌다.
//! · **값인 0.** 위 둘을 재다가 진짜 술어 하나가 잡혔다 — **하한을 인자로 받은 자리가
//!   그것을 순회로 보내는가.** 순회 정의 자신을 빼고 클로저까지 넣은 모수 **15** 에서,
//!   받아 놓고 순회에도 안 보내고 다른 함수로 넘기지도 않는 자리가 **0** 이다. 이것은
//!   대리가 아니라 물음 그대로이고, 그래서 값이다.
//!
//! ## 두 「도달」이 같은 낱말의 다른 물음이다
//!
//! 같은 회차에 다른 축에서도 도달을 물었다 — 하한 선언이 검사 함수에 **도달하는가**.
//! 그쪽은 문자열로 안 세어진다고 판정됐다. 여기서는 세어졌다. 갈리는 자리가 있다:
//!
//! **인자 자리로 흐르는 도달은 구문이고, 호출 경로로 흐르는 도달은 구문이 아니다.**
//! 하한이 순회에 닿는지는 인자의 몇 번째 자리에 그 이름이 있는가로 답이 나서 한 파일
//! 안에서 끝난다. 하한이 검사에 닿는지는 **누가 그 함수를 부르는가**에 달렸고, 그것은
//! 파일을 넘고 조건을 넘는다. 같은 낱말을 쓰면 한쪽의 0 을 다른 쪽 근거로 쓰게 된다.
//!
//! ## 이 축에서도 판정기는 안 짓는다 — 칸은 **좌변**이다
//!
//! 값인 0 이 나왔으니 셀 것이 없다. 0 을 값으로 적는 것이 처방이다. 앞의 두 축이 소유
//! 때문에 멈춘 것과 다른 칸이고, 그래서 재진입 조건도 다르다: **그 15 가 늘면서 순회로
//! 안 보내는 자리가 하나라도 생기면.** 지금 15 라는 것도 함께 적어 둔다 — 좌변이 0 인
//! 것과 모수가 0 인 것은 다르고, 그 둘을 가르는 것은 모수를 적어 두는 일뿐이다.
//!
//! ## 도구 결함 (둘째 회차 연속 같은 자리)
//!
//! 첫 판이 **또 클로저를 안 봤다.** 뿌리 축에서 같은 결함을 적어 두고도 다음 축의 도구를
//! 같은 형태로 지었다 — 적어 두는 것이 다시 안 밟게 해 주지 않는다는 실례다. 그리고
//! 순회 함수 **자신의 정의**를 모수에 넣었다: 그 둘은 하한을 순회로 보내는 것이 아니라
//! 하한을 **쓰는** 자리라, "안 닿음" 으로 세어졌다. 고치기 전 모수 16 · 고친 뒤 15 이고,
//! 사라진 둘과 들어온 하나가 서로를 상쇄해 **합계가 하나밖에 안 움직였다** — 두 결함이
//! 반대 방향이라 합계만 보면 둘 다 안 보였다.
//!
//! # 좌표 규약 — 이 조사가 적은 트리 이름을 영구 좌표로 바꾼다
//!
//! 회차는 체리픽으로 착지한다. 그래서 **lane 의 마지막 커밋은 주 가지의 조상이 절대
//! 안 된다** — 그 워크트리를 다음 회차 기점으로 옮기는 순간 그 해시는 어느 이름으로도
//! 안 잡히고 수거된다. "값 옆에 잰 트리를 적어라" 는 규율은 옳았고, 어긋난 것은 **그
//! 좌표가 영구한 이름이라는 가정**이다. 합쳐서 착지하면 참이고 골라서 착지하면 거짓이다.
//!
//! 그래서 이제 이렇게 적는다: 회차 기점 그대로의 값은 **기점 해시**로, 내 커밋이 얹힌
//! 값은 **기점 해시 + 내 커밋 몇 개**로, 합성 픽스처가 자기가 만든 트리를 잰 값은 **트리
//! 좌표를 아예 안 적는다**(물음이 성립하지 않는다). 위 두 축이 "회차 95 기점" 이라고
//! 말로만 적었던 자리에 기점 해시를 박았다 — 말은 회차가 지나면 찾아야 하는 것이 된다.
//!
//! ## 이 규약의 실물이 이 조사의 값 하나다
//!
//! 뿌리 축에서 같은 것을 세는 하한 둘이 448 과 440 이라 적었고, 차 여덟이 거르개가
//! 아니라 잰 트리에서 왔다고 갈랐다. 그 트리들이 이제 이름을 얻었다 — 같은 술어의 값이
//! **440 · 445 · 448 · 453** 넷이고, 448 과 440 은 각각 **자기 lane 의 마지막 커밋**에서
//! 잰 값이다. 둘 다 지금은 틀렸고, 그 좌표는 곧 사라진다.
//!
//! 내가 잰 두 값(445 와 453)은 우연히 둘 다 살아남는다. **우연이 아니라 방법 때문이다.**
//! 나는 두 번 다 트리를 통째로 **뽑아서** 쟀고, 뽑으려면 어느 지점을 뽑을지 반드시 골라야
//! 한다. 작업 트리에서 그냥 세면 그 트리가 무엇인지 **안 묻게 된다** — 답이 이미 거기
//! 있으니 물음이 안 생긴다. 규율이 방법을 정하는 것이 아니라 **방법이 규율을 강제한 자리**다.
//!
//! ## 이미 적은 것은 고치지 않는다 — 다만 무엇이었는지는 여기 적는다
//!
//! 위 뿌리 축이 "통합 회차의 사본" 이라고만 적은 자리는 그대로 둔다. 지우면 그때 무엇을
//! 보고 판단했는지가 사라지고, 그 판단이 틀렸다면 틀린 이유도 같이 사라진다. 대신 지금
//! 이름을 붙여 둔다: 그 사본은 회차 94 통합분이 그대로 주 가지에 오른 것이고, 그 트리에서
//! 잰 문서 수가 453 이다. 회차 94 의 내 작업 트리에서 잰 445 는 그 회차 기점의 값과 같다 —
//! 내 커밋이 그 모수에 아무것도 안 더했기 때문이고, **그것도 값이라 함께 적는다.**
//!
//! # 하한이 지키는 집합과 단정이 보는 집합이 어긋나는 자리
//!
//! 다른 축에서 실물이 하나 나왔다 — 하한 상수가 **있는데도** 부분 소실에 안 죽는 가드.
//! 여유가 흡수한 것이 아니라 **그 상수가 재는 모수가 그 물음의 모수가 아니다.** 내
//! 하한 축에서 같은 형태를 셀 수 있는지 물었고, 셀 수 있었다. 잰 트리는 회차 95 기점
//! `12bc0f4b2` 의 사본이다.
//!
//! ## 두 형태를 먼저 가른다
//!
//! · **모수 불일치** — 하한이 **애초에 다른 것**을 잰다. 위의 실물이 그것이다.
//! · **모수 누수** — 하한과 단정이 **같은 것**을 재는데, 하한을 통과한 뒤 산출물이 조용히
//!   줄어든다. 이 레포는 이 형태를 이미 알고 네 자리에 주석으로 적어 두었다: 읽기 실패를
//!   건너뛰면 순회 하한을 통과한 채 본문만 비는 길이 남고, **하한이 세는 것은 찾은
//!   파일이지 읽은 파일이 아니다.**
//!
//! 둘은 같은 병의 두 얼굴이다 — 하한이 지키는 집합과 단정이 보는 집합이 어긋난다.
//! 앞의 것은 처음부터 어긋나 있고, 뒤의 것은 도중에 어긋난다.
//!
//! ## 좌변이 네 번 좁혀졌다 — 매번 앞 술어가 대리여서
//!
//! | 술어 | 값 |
//! |---|---|
//! | 하한이 있는 가드에서 파일을 다시 읽는 자리 | 59 |
//! | 그중 **순회 산출물의 경로**를 읽는 자리 | 21 |
//! | 그중 실패를 **조용히** 넘기는 자리 | 13 |
//! | 그중 순회에 **확장자 조건이 없는** 자리 | **4** |
//!
//! 세 번의 좁힘이 전부 같은 이유다. 59 는 고정 경로 파일 읽기를 함께 셌다 — 순회 모수와
//! 무관한 자리다. 21 은 실패를 패닉으로 막은 자리를 함께 셌다 — 이 레포가 이미 처방을 쓴
//! 여섯이 거기 있다. 13 은 **실패할 수 있는가**를 안 물었다: 순회가 확장자로 좁혀져 있으면
//! 텍스트로 못 읽는 파일이 애초에 안 들어온다.
//!
//! **마지막 4 도 상한이지 결함 목록이 아니다.** 확장자 조건이 없다는 것은 실패가 **가능**
//! 하다는 뜻이지 실재한다는 뜻이 아니다. 실재를 보려면 그 뿌리에 텍스트 아닌 파일이 실제로
//! 있는지를 뿌리마다 세야 하고, 그것은 안 쟀다.
//!
//! ## 「대리 술어의 0」은 이미 내 갈래에 있다
//!
//! 다른 축에서 같은 경고가 왔다 — 오늘 잰 것은 대리 술어이고 그 0 을 「없다」로 읽지
//! 마라. 앞 절에서 0 을 셋으로 가를 때 **첫째 갈래의 이름이 이미 그것**이다. 넷째 칸은
//! 필요 없고, 필요한 것은 그 갈래가 **다른 사람의 축에서도 같은 이름으로 불리는가**였다.
//! 불린다 — 두 축이 서로 모르고 같은 이름에 도달했으니 그것이 그 갈래가 실재한다는 증거다.
//!
//! ## 판정기 — 안 짓는다. 칸은 또 **소유**다 (셋째 실례)
//!
//! 좌변 4 · 처방(확장자로 안 좁힌 순회의 산출물을 읽을 때 실패를 조용히 넘기지 마라) ·
//! 방향 한쪽이 다 선다. 레포가 이미 여섯 자리에서 그 처방을 썼으니 처방이 옳다는 증거도
//! 있다. 막은 것은 그 넷이 사는 파일이 이 회차에 내 것이 아니라는 것뿐이다.
//!
//! 소유 칸의 셋째 실례다. 앞의 둘과 다른 점이 하나 있다 — 앞의 둘은 좌변을 고치는 데
//! 남의 파일이 필요했는데, 여기서는 **좌변을 좁히는 데에도** 남의 파일을 읽어야 했다.
//! 읽는 것은 소유와 무관해서 좁힐 수 있었고, 그래서 넘길 때 좌변이 13 이 아니라 4 다.
//!
//! ## 도구 결함 (셋째 회차 연속 같은 계열)
//!
//! 첫 판이 **주석을 안 걷었다.** doc 주석 안에서 함수 이름을 산문으로 인용한 자리가 읽기
//! 자리로 세어졌다. 뿌리 축에서는 클로저를 안 봤고, 정책 축에서도 또 클로저를 안 봤고,
//! 여기서는 주석을 안 걷었다 — 셋 다 **덮은 사본을 안 쓴 대가**다. 그런데 이 조사는
//! 덮은 사본을 쓸 수가 없다: 뿌리도 정책도 이름이라 덮으면 사라진다. **사본을 못 고르는
//! 물음에서는 도구가 매번 같은 값을 다시 잃는다** — 그것이 이 세 결함의 공통 원인이다.
//!
//! # ★ 강한 형태를 채널로 넘긴 결정이 틀렸다 — 그런 채널이 아니었다
//!
//! 이 판정기가 강한 형태(하한을 인자로 받아 놓고 아예 안 쓰는 것)를 안 세는 이유로
//! **채널**을 들었다: 컴파일러의 미사용 인자 경고가 이미 그 자리에서 답을 낸다고.
//! 그리고 그 채널이 사라지는 길을 재진입 조건으로 걸었다. **전제가 틀렸다.**
//!
//! 워크스페이스가 거부 수준으로 못 박은 진단 목록에 **미사용 인자가 없다.** 못 박힌 것은
//! 죽은 대입 · 죽은 코드 · 무시된 결과 등이고, 미사용 인자는 그 목록 밖이라 **경고로만
//! 난다.** 그리고 통합 검사는 경고를 오류로 올리지 **않는다** — 워크플로 주석이 그 이유를
//! 명시한다: 의도적 경고가 여럿이라 그렇게 하면 검사가 상시 빨개진다.
//!
//! 그러니 그 자리에서 나오는 것은 **진단이지 거부가 아니다.** 아무 빌드도 안 막고, 아무
//! 검사도 안 죽인다. 채널이 **사라진** 것이 아니라 **애초에 그런 채널이 아니었다.**
//!
//! ★ **컴파일러가 잡는다를 채널로 쓰려면 그 진단이 무엇을 막는지 확인해야 한다 — 경고와
//! 거부는 다른 채널이다.** 나는 진단이 난다는 것만 보고 채널로 닫았다.
//!
//! ## 그리고 이것을 "못 쟀다" 로 닫은 것도 틀렸다
//!
//! 앞 절에서 이 갈래를 대리 술어의 0 으로 적으며 "빌드 설정의 성질이라 소스 문자열로 안
//! 세어진다 — 못 쟀다" 고 했다. **못 잰 것이 아니었다.** 워크스페이스 설정 하나와 검사
//! 설정 하나, 두 파일에 평문으로 적혀 있다. 소스 문자열이 아니라는 판단이 **찾아보는
//! 일을 건너뛰게 했다.** 못 잰다는 말도 값이라 함부로 적으면 안 된다 — 그 말이 다음
//! 사람에게는 "여기는 볼 것이 없다" 로 읽힌다.
//!
//! ## 결정은 그대로, 칸과 재진입 조건이 바뀐다
//!
//! 판정기는 여전히 안 짓는다. 그런데 이유가 채널이 아니라 **좌변**이다 — 앞 절에서 이미
//! 쟀듯 하한을 인자로 받은 자리 15 중 그것을 안 쓰는 자리가 0 이다. 그래서 재진입 조건도
//! 바뀐다: "채널이 사라지면" 이 아니라 **"강한 형태가 하나라도 나타나면"** 이다.
//!
//! 두 조건의 실질 차이가 크다. 채널로 닫았을 때는 채널이 지켜 주는 줄 알았는데, 실제로는
//! **아무도 안 막는다.** 강한 형태가 새로 들어와도 경고 한 줄이 흘러갈 뿐 어느 검사도
//! 안 죽는다. 좌변으로 닫으면 그 사실이 드러난다 — 0 을 지키는 것이 채널이 아니라 **아무것도
//! 아니라는 것**이.
//!
//! # lane 모수 — 좌변이 lane 트리마다 다른 값을 내는 자리
//!
//! 통합에서 새 형태가 나왔다. 같은 모수를 두 lane 이 각자 자기 트리에서 재서 **둘 다 같은
//! 값을 적었는데 둘 다 틀린** 자리다. 둘 다 자기 트리에서는 참이었다. 지금까지 "값이
//! 낡았다" 로 다뤄 온 것과 처방이 다르다 — 낡은 값은 다시 재면 맞고, 이것은 **lane 에서는
//! 원리적으로 못 맞춘다.** 통합만이 잴 수 있다.
//!
//! 내 하한 축에서 이 형태를 셌다. 이번 회차 여덟 갈래가 기점에 더한 파일을 모수별로
//! 갈랐더니, **갈린 모수는 하나**다 — 크레이트 아래 시험 타깃. 세 갈래가 각각 하나씩
//! 더했다. 문서 · 소스 · 스크립트 · 번역 · 검사 설정 · 가이드는 이번 회차에 **아무도
//! 안 더했다.**
//!
//! ★ **그래서 이 형태는 모수의 성질이 아니라 회차의 성질이다.** 바로 앞 회차에는 문서
//! 모수가 갈렸다 — 그 회차의 갈래들이 결정 기록을 여덟 개 더했고, 그것이 내가 뿌리 축에서
//! 448 과 440 의 차로 본 바로 그것이다. **같은 모수가 회차마다 편을 바꾼다.**
//!
//! 그래서 답이 하나의 수가 아니다.
//!
//! · **실측(이 회차)**: 갈린 모수 **1**.
//! · **원리(뿌리가 갈래 산출물을 담을 수 있는가)**: 서른둘 중 **25**. 나머지 일곱은 검사
//!   설정 셋 · 가이드 둘 · 번역 둘로, 그 뿌리에 파일을 더하는 것이 회차 작업이 아니다.
//! · **둘의 차 24 가 이 갈래의 성질이다.** 원리적으로 갈릴 수 있는 모수 대부분이 어느
//!   회차에는 안 갈린다. 그 회차에 그 뿌리를 건드리는 축이 배정됐는가에 달렸다.
//!
//! ## 그래서 갈래는 회차 시작에 안다
//!
//! 처방이 "통합이 잰다" 로 끝나면 갈래가 할 일이 없어 보이는데, 하나 있다. **어느 모수가
//! 이번 회차에 갈릴지는 회차 시작에 이미 정해져 있다** — 소유표가 축을 배정하는 순간
//! 그 뿌리에 파일이 더해질지가 정해진다. 그러니 값을 적기 전에 그 뿌리를 건드리는 축이
//! 나 말고 있는지를 보고, 있으면 **값을 못 박지 말고 통합에 넘긴다.** 실측이 이 회차에
//! 하나뿐인 것도 그래서다 — 스물다섯 중 스물넷은 이번에 아무 축도 그 뿌리를 안 건드렸다.

use std::collections::BTreeSet;

use super::{mask_non_code, matching_delim, rust_sources_with_integration_tests, word_positions};

/// 첫째 축의 인자 타입 이름. 문자열로 두는 것이 중요하다 — 이 판정기 자신의 소스가
/// 좌변에 있으므로, 형태를 코드로 적으면 자기 자신을 세게 된다. 마스킹이 문자열을
/// 지우므로 이렇게 두면 안 세어진다.
const FLOOR_TYPE: &str = "Floor";

/// 둘째 축이 기대는 이름 관례 — 하한 상수의 접두와, 하한 인자 이름에 들어가는 조각.
const MIN_CONST_PREFIX: &str = "MIN_";
const FLOOR_PARAM_HINTS: &[&str] = &["floor", "min"];

/// 모수 하한. 2026-09-08 에 **이 판정기 자신으로** 이 브랜치의 base 에서 잰 값이고,
/// 사본은 이 판정기가 쓰는 것 — 코드가 아닌 부분을 덮은 것이다.
/// 같은 술어를 통합 트리(그 시점의 통합 브랜치)에 대고 재면 타입 축이 둘 더 많았다 —
/// 그쪽이 추출을 둘 더 담고 있기 때문이다. 하한이라 통합 쪽이 커도 초록이다.
///
/// **값이 어느 트리에서 나왔는지를 값 옆에 남긴다.** 남기지 않으면 다음 사람이 자기
/// 트리에서 재고 이 수와 견준다.
///
/// 처음에 이 수를 다른 도구로 재서 12 를 얻었는데, 그 도구는 참조로 받는 인자만
/// 셌고 이 판정기는 값으로 받는 것도 센다. 두 술어의 값이 우연히 같았다 — **맞는 수가
/// 틀린 이유로 서 있는 자리**였고, 이 판정기 자신으로 다시 재서 갈랐다.
///
/// 위쪽으로는 안 막는다. 추출이 진행되면 모수는 는다. 줄면 빨간데, 그때 뜻하는 것은
/// 회귀가 아니라 **추출이 되돌려졌거나 술어가 낡았다** 는 것이고 둘 다 사람이 봐야 한다.
const MIN_TYPED_FLOOR_PARAMS: usize = 12;
const MIN_NAMED_FLOOR_PARAMS: usize = 6;

/// 한 파일에서 (모듈 상수 이름 집합, 그 축의 인자를 받는 함수들).
struct Axis {
    consts: BTreeSet<String>,
    fns: Vec<(String, String)>,
}

/// `masked` 안의 `const`/`static` 선언 중 타입이 `ty` 인 것의 이름.
fn consts_typed(masked: &str, ty: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for kw in word_positions(masked, "const")
        .into_iter()
        .chain(word_positions(masked, "static"))
    {
        let rest = &masked[kw..];
        let Some(colon) = rest.find(':') else {
            continue;
        };
        let Some(eq) = rest.find('=') else { continue };
        if colon > eq {
            continue;
        }
        let name: String = rest[..colon]
            .rsplit(|c: char| c.is_whitespace())
            .next()
            .unwrap_or("")
            .to_string();
        let declared = rest[colon + 1..eq].trim().trim_start_matches('&').trim();
        if declared == ty && !name.is_empty() {
            out.insert(name);
        }
    }
    out
}

/// 이름이 `MIN_CONST_PREFIX` 로 시작하고 타입이 `usize` 인 모듈 상수의 이름.
fn min_consts(masked: &str) -> BTreeSet<String> {
    consts_typed(masked, "usize")
        .into_iter()
        .filter(|n| n.starts_with(MIN_CONST_PREFIX))
        .collect()
}

/// `fn` 하나의 (이름, 인자 목록, 본문). 본문 없는 선언은 건너뛴다.
fn fn_parts(masked: &str) -> Vec<(String, String, String)> {
    let mut out = Vec::new();
    for kw in word_positions(masked, "fn") {
        let after = kw + "fn".len();
        let name: String = masked[after..]
            .chars()
            .skip_while(|c| c.is_whitespace())
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect();
        if name.is_empty() {
            continue;
        }
        let Some(open) = masked[after..].find('(').map(|i| i + after) else {
            continue;
        };
        let Some(close) = matching_delim(masked, open) else {
            continue;
        };
        let Some((bo, bc)) = super::block_after(masked, close + 1) else {
            continue;
        };
        out.push((
            name,
            masked[open + 1..close].to_string(),
            masked[bo..bc].to_string(),
        ));
    }
    out
}

/// 파일 하나를 두 축으로 읽는다.
fn axes_of(masked: &str) -> (Axis, Axis) {
    let typed = consts_typed(masked, FLOOR_TYPE);
    let named = min_consts(masked);
    let (mut ta, mut na) = (Vec::new(), Vec::new());
    for (name, params, body) in fn_parts(masked) {
        if takes_typed_floor(&params) {
            ta.push((name.clone(), body.clone()));
        }
        if takes_named_floor(&params) {
            na.push((name, body));
        }
    }
    (
        Axis {
            consts: typed,
            fns: ta,
        },
        Axis {
            consts: named,
            fns: na,
        },
    )
}

/// 인자 목록에 `<이름>: &<하한 타입>` 이 있는가.
fn takes_typed_floor(params: &str) -> bool {
    params.split(',').any(|p| {
        let Some((_, ty)) = p.split_once(':') else {
            return false;
        };
        ty.trim().trim_start_matches('&').trim() == FLOOR_TYPE
    })
}

/// 인자 목록에 이름이 하한을 가리키는 `usize` 인자가 있는가.
fn takes_named_floor(params: &str) -> bool {
    params.split(',').any(|p| {
        let Some((name, ty)) = p.split_once(':') else {
            return false;
        };
        if ty.trim() != "usize" {
            return false;
        }
        let name = name.trim().to_ascii_lowercase();
        FLOOR_PARAM_HINTS.iter().any(|h| name.contains(h))
    })
}

/// 본문이 이름으로 부르는 상수들.
fn discarded(body: &str, consts: &BTreeSet<String>) -> Vec<String> {
    consts
        .iter()
        .filter(|c| !word_positions(body, c).is_empty())
        .cloned()
        .collect()
}

/// (파일, 함수 이름, 본문이 다시 읽는 상수들).
type Hit = (String, String, Vec<String>);

/// 판정 대상 전부를 한 번만 읽어 두 축으로 접는다. **사본은 하나다** — 축마다 파일을
/// 다시 읽으면 같은 물음에 답이 둘이 될 수 있다.
fn scan() -> (Vec<Hit>, [usize; 2]) {
    let mut hits: Vec<Hit> = Vec::new();
    let mut counts = [0usize; 2];
    for (path, src) in rust_sources_with_integration_tests() {
        let rel = path.to_string_lossy().into_owned();
        let masked = mask_non_code(&src);
        let (typed, named) = axes_of(&masked);
        for (axis, a) in [typed, named].into_iter().enumerate() {
            counts[axis] += a.fns.len();
            for (name, body) in &a.fns {
                let taken = discarded(body, &a.consts);
                if !taken.is_empty() {
                    hits.push((rel.clone(), name.clone(), taken));
                }
            }
        }
    }
    (hits, counts)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 하한을 인자로 받는 함수가 같은 축의 모듈 상수를 다시 읽지 않는다.
    #[test]
    fn a_floor_taken_as_an_argument_is_not_replaced_by_the_module_constant() {
        let (hits, counts) = scan();
        assert!(
            counts[0] >= MIN_TYPED_FLOOR_PARAMS && counts[1] >= MIN_NAMED_FLOOR_PARAMS,
            "모수가 줄었다 — 타입 축 {} (하한 {MIN_TYPED_FLOOR_PARAMS}) · 이름 축 {} \
             (하한 {MIN_NAMED_FLOOR_PARAMS}). 회귀가 아니라 추출이 되돌려졌거나 이 \
             판정기의 술어가 낡은 것이다. 빈 좌변의 초록은 통과가 아니라 미측정이다",
            counts[0],
            counts[1]
        );
        assert!(
            hits.is_empty(),
            "하한을 **인자로 받아 놓고** 본문에서 모듈 상수를 다시 읽는 자리가 있다. \
             그러면 합성 트리를 넘겨도 정본 하한이 적용되고, 대체 가능해졌다는 주장만 \
             남는다 — 인자를 그대로 써라: {hits:?}"
        );
    }

    /// 양성 대조 — 이 판정기가 실제로 그 형태를 잡는가.
    ///
    /// 픽스처를 이 판정기의 상수로 만들지 않는다. 자기 상수로 만든 픽스처는 동어반복이라
    /// 술어가 틀려도 통과한다(R1078). 아래 이름들은 이 레포 어디에도 없는 것이다.
    #[test]
    fn the_shape_this_judges_is_actually_caught() {
        let bad = format!(
            "const HOUSE_LIMIT: {FLOOR_TYPE} = make();\n\
             fn read_under(root: &Path, limit: &{FLOOR_TYPE}) {{\n\
             \x20   walk(root, &HOUSE_LIMIT)\n\
             }}\n"
        );
        let (typed, _) = axes_of(&mask_non_code(&bad));
        assert_eq!(typed.fns.len(), 1, "모수를 못 잡았다");
        assert_eq!(
            discarded(&typed.fns[0].1, &typed.consts),
            vec!["HOUSE_LIMIT".to_string()],
            "인자를 버리는 형태를 안 잡았다"
        );

        let bad_named = format!(
            "const {MIN_CONST_PREFIX}HOUSES: usize = 9;\n\
             fn read_under(root: &Path, floor: usize) {{\n\
             \x20   walk(root, {MIN_CONST_PREFIX}HOUSES)\n\
             }}\n"
        );
        let (_, named) = axes_of(&mask_non_code(&bad_named));
        assert_eq!(named.fns.len(), 1, "이름 축 모수를 못 잡았다");
        assert_eq!(
            discarded(&named.fns[0].1, &named.consts),
            vec![format!("{MIN_CONST_PREFIX}HOUSES")],
            "이름 축에서 인자를 버리는 형태를 안 잡았다"
        );
    }

    /// 음성 대조 — **정상 형태인 겉/속 짝을 안 잡는다.**
    ///
    /// 겉함수는 상수를 읽는 것이 일이다. 그것을 잡으면 이 판정기는 리팩터를 금지하는
    /// 가드가 된다. 모수를 "그 축의 인자를 받는 함수" 로 정의한 것이 이 구분을 만든다 —
    /// 겉함수는 그 인자를 안 받으므로 애초에 모수 밖이다.
    #[test]
    fn the_intended_outer_and_inner_pair_is_not_caught() {
        let good = format!(
            "const HOUSE_LIMIT: {FLOOR_TYPE} = make();\n\
             fn read(root: &Path) {{ read_under(root, &HOUSE_LIMIT) }}\n\
             fn read_under(root: &Path, limit: &{FLOOR_TYPE}) {{ walk(root, limit) }}\n"
        );
        let (typed, _) = axes_of(&mask_non_code(&good));
        assert_eq!(
            typed.fns.len(),
            1,
            "겉함수가 모수에 들어왔다 — 이 판정기는 정상 형태를 금지하게 된다"
        );
        assert_eq!(
            typed.fns[0].0, "read_under",
            "모수에 든 것이 속함수가 아니다"
        );
        assert!(
            discarded(&typed.fns[0].1, &typed.consts).is_empty(),
            "인자를 그대로 쓰는 속함수를 잡았다"
        );
    }

    /// 상수가 하나도 없는 파일에서 조용히 빈 집합으로 통과하지 않는다 — 모수는 상수가
    /// 아니라 **인자**로 세므로, 상수 0 인 파일의 함수도 모수에 들어와야 한다.
    #[test]
    fn the_population_is_counted_by_arguments_not_by_constants() {
        let no_const =
            format!("fn read_under(root: &Path, limit: &{FLOOR_TYPE}) {{ walk(root, limit) }}\n");
        let (typed, _) = axes_of(&mask_non_code(&no_const));
        assert_eq!(typed.consts.len(), 0, "상수가 없어야 하는 픽스처다");
        assert_eq!(
            typed.fns.len(),
            1,
            "상수가 없다고 모수에서 뺐다 — 그러면 상수를 나중에 들이는 변경이 안 보인다"
        );
    }
}
