#!/usr/bin/env bash
# 통합 테스트 타깃이 **직접** 트리를 순회하는 자리를 센다. 공용 순회
# (`tasty_doc_guards::floored_walk::walk_with_floor`)로 옮길 수 있는 것들이고, 옮기면
# 하한을 빠뜨릴 수 없게 된다.
#
# ── 무엇을 세는가, 그리고 왜 이 모수인가 ────────────────────────────────────
# 좌변은 `tests/*.rs` 와 `crates/*/tests/*.rs` 의 **한 겹**이다. cargo 가 이 디렉토리의
# 각 `.rs` 를 통합 테스트 타깃으로 자동 등록하므로, 좌변에서 빠뜨린 파일은 조용히
# 통과하는 것이 아니라 **아예 안 도는 파일**이다 — 빠뜨림이 시끄럽다.
#
# ★ 단, 그 논증은 **cargo 의 모수**(디렉토리에 실재하는 파일)에 대해 참이고 이 좌변은
#   **git 의 모수**(인덱스)다. 둘은 **미추적 창에서 갈린다** — 아직 `git add` 안 한
#   `.rs` 는 cargo 가 타깃으로 등록해 **돌지만** `git ls-files` 는 안 낸다. 그 창에서
#   이 게이트는 그 파일의 순회를 **안 센다**. 실측: `tests/` 에 `read_dir(` 하나를 담은
#   미추적 파일을 두고 돌리면 58 이 아니라 **57 로 나오고 rc=0** 이다(상한과 같으니
#   초록이다). 즉 위 "빠뜨림이 시끄럽다" 는 그 창 안에서 **성립하지 않는다.**
#   ☆ 하필 그 창이 **새 가드를 짓는 동안**이고, 다른 게이트(fmt·clippy·cargo test)는
#     디렉토리를 보므로 새 파일을 곧바로 센다. 이 하나만 다르게 대답해서 알아채기 어렵다.
#   ☆ 그 창은 이제 **판정 불가로 닫혀 있다**(아래 미추적 검사, rc=2). 좌변은 여전히
#     인덱스지만, 둘이 갈린 상태에서는 값을 내지 않는다.
#
# 이 좌변을 고른 이유가 하나 더 있다. 같은 물음을 "레포 루트에 매인 순회" 로 잡으면
# 그 갈래를 문자열 술어로 갈라야 하고(뿌리를 어디서 얻는가, 재귀 신호가 있는가),
# 그런 술어는 **추상화한 쪽을 체계적으로 놓치면서 그 방향이 조용하다.** 래칫의 좌변이
# 조용한 방향으로 틀리면 래칫 자신이 그 방향으로 조용해진다. 반면 배치로 가르면
# 런타임 파일시스템을 읽는 프로덕션 코드(사용자 홈·`/proc`·플러그인 디렉토리)가
# **판정 없이** 빠진다 — 프로덕션 코드는 `tests/` 에 없다. 근거와 갈래별 실측은
# docs/dev-guide/guard-population.md 의 "직접 `read_dir` 을 쓰는 자리".
#
# ── 이 수는 **하한이다** ────────────────────────────────────────────────────
# 술어가 세는 것과 이 게이트가 막으려는 것이 같다(직접 순회 자리 자신). 즉 이 수는
# **찾은 것**이라, 술어가 덜 찾으면 값이 실제보다 작아진다 — 위 잔여처럼 부풀지
# 않는다. 그래서 `read_dir(` 이라는 철자로 안 써진 순회 형태는 상한에 안 들어가고,
# 그 형태를 새로 들이는 변경은 이 게이트를 조용히 지나간다. 아래 "못 보는 것" 은
# 좌변(어느 파일을 보는가)의 사각이고, 이것은 **철자**의 사각이라 다른 축이다.
#
# ── 단위: 호출 자리 (파일이 아니다) ─────────────────────────────────────────
# 지키려는 것은 **순회 하나하나**다. 한 파일이 순회를 하나 더 얻으면 위험도 하나 는다.
# 파일 단위로 세면 같은 파일 안의 증감을 전혀 못 본다. 반대로 한 파일이 재귀 헬퍼를
# 안에서 공유해 소비자 둘을 먹이는 경우가 있는데, 그때는 **순회가 하나**라 위험도
# 하나다 — 호출 자리가 그것을 맞게 센다.
#
# 단위를 바꾸면 수가 얼마나 움직이는지 재서 적는다. 안 재고 고르면 "무엇을 세는가" 가
# 이름에만 있고 값에는 없다.
#
#     2026-09-06 실측, 같은 좌변:   호출 자리 57 · 파일 38
#
# 파일 단위는 **33% 낮은 수**를 낸다(−19). 그 19 는 오차가 아니라 파일 단위가 버리는
# 정보 그 자체다 — 순회를 둘 이상 가진 파일이 13 개이고, 거기서는 순회가 하나 늘거나
# 줄어도 파일 수가 안 움직인다. 가장 밀집한 둘은 각각 넷을 갖는다
# (`tests/i18n_key_parity.rs` · `crates/tasty-doc-guards/tests/ci_channel_claims_match_workflows.rs`).
# 나머지 25 개 파일은 하나씩이라 두 단위가 같은 값을 낸다.
#
# ★ 그러니 파일 단위를 골랐다면 상한을 38 로 **내려서** 잡아야 했고, 그 순간 저 13 개
#   파일 안의 증가는 영구히 안 보이게 된다. 낮은 수가 더 엄격해 보이지만 여기서는 반대다.
#
# ── 왜 hard-fail 이 아니라 래칫인가 ────────────────────────────────────────
# 잔여가 0 이 아니다. 0 을 요구하면 main 이 그 자리에서 빨개지고, 리포트로 두면 건수와
# 무관하게 늘 통과하는 칸이 하나 생긴다. 그래서 상한을 박은 래칫이다.
#   늘면        실패한다 — 새 순회가 공용 순회를 안 거치고 들어온 것이다.
#   줄면        실패한다 — 상한을 같이 내리라는 뜻이다. 여유는 곧 안 보는 구간이다.
#   스캐너가 깨지면 실패한다 — `set -euo pipefail` 로 그 자리에서 죽는다.
#
# ── 이 래칫이 못 보는 것 (가짜로 덮지 않는다) ───────────────────────────────
# `src/` 안의 `#[cfg(test)]` 유닛 테스트로 순회를 옮기면 이 수가 **안 움직인다.**
# 그 형태는 가정이 아니라 실재한다 — `src/source_guards/` 의 가드들이 그 모양이다.
# 그 갈래를 덮으려면 "순수 소스 스캔인가" 를 판정하는 술어를 공용으로 올려야 하는데,
# 그 술어는 지금 통합 테스트 안의 private fn 이라 **다른 타깃에서 부를 수 없다.**
# 그것이 선행 조건이고, 그 전까지 이 갈래를 재는 채널은 **없다.**
#
# 채널: .github/workflows/script-gates.yml (main push · PR)
# 사용: scripts/check-shared-walk-ratchet.sh

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# 한 겹만 — 하위 디렉토리의 `.rs` 는 타깃이 아니라 그 타깃이 쓰는 모듈이다. git 의 pathspec
# 에서 `*` 는 `/` 도 먹으므로 깊이는 여기서 따로 거른다.
FILES=$(git ls-files -- 'tests/*.rs' 'crates/*/tests/*.rs' \
    | grep -E '^(tests/[^/]+\.rs|crates/[^/]+/tests/[^/]+\.rs)$' || true)

if [ -z "$FILES" ]; then
    echo "통합 테스트 타깃을 하나도 못 찾았다 — 좌변이 깨졌다. 이 상태의 0 은 '직접"
    echo "순회가 없다' 가 아니라 '아무것도 안 봤다' 다."
    exit 1
fi

# ── 아직 인덱스에 없는 타깃이 있으면 판정하지 않는다 ────────────────────────
# 위 좌변은 git 의 모수(인덱스)이고 cargo 의 모수는 디렉토리 실물이다. 미추적 `.rs` 가
# 있는 동안 둘이 갈린다 — 그 파일은 타깃으로 **돌면서** 여기서는 안 세어진다. 그 창이
# 하필 새 가드를 짓는 동안이고, 다른 게이트(fmt·clippy·cargo test)는 디렉토리를 보므로
# 같은 순간에 정상으로 답한다. 그래서 "다섯 중 넷이 새 파일을 봤으니 다섯째도 봤겠지"
# 가 성립하지 않는다.
#
# 범위는 **좌변과 같게** 잡는다. 미추적 `.rs` 아무거나가 아니라 위 pathspec 이 보는
# 한 겹만이다 — 무관한 스크래치가 이 게이트를 빨갛게 만들면 그 빨강이 진짜 신호를 묻는다.
UNTRACKED=$(git ls-files --others --exclude-standard -- 'tests/*.rs' 'crates/*/tests/*.rs' \
    | grep -E '^(tests/[^/]+\.rs|crates/[^/]+/tests/[^/]+\.rs)$' || true)

if [ -n "$UNTRACKED" ]; then
    echo "인덱스에 없는 통합 테스트 타깃이 있다 — 이 상태에서는 판정하지 않는다."
    echo "이 파일들은 cargo 가 타깃으로 등록해 돌지만 좌변이 못 본다. 지금 세면 그 순회가"
    echo "빠진 수가 나오고, 그 수가 상한과 같으면 초록이 거짓이 된다."
    printf '%s\n' "$UNTRACKED" | sed 's/^/  /'
    echo "git add 한 뒤 다시 돌려라."
    exit 2
fi

# ── 문자열·주석을 덮은 사본에서 센다 ────────────────────────────────────────
# 이 검사는 텍스트 스캔이라 타입을 모른다. 원문에서 세면 **주석과 문자열 안의 언급까지**
# 실물로 센다 — 이 레포에는 그 형태가 실재한다(순회 수단을 설명하는 주석, 그리고
# 가드의 회귀 픽스처가 담는 문자열). 판정을 셸에서 다시 구현하지 않는다: 러스트 층이
# 이미 그 판정을 갖고 있고, 셸이 자기 렉서를 만들면 같은 물음에 답이 둘이 된다.
#
# 판정기가 없으면 원문에서 센다 — 그쪽은 **더 많이 세는** 방향이라 조용한 통과를 안
# 만든다. 다만 래칫이라 넘치면 실패한다. 그래서 자동 채널이 판정기를 먼저 짓는다.
#
# 2026-09-06 실측: 원문 58 · 사본 57. 차 하나는
# `crates/tasty-doc-guards/tests/file_walks_declare_their_mechanism.rs` 의 명부가 이
# 낱말을 **문자열로** 담고 있어서다(그 가드의 판정 대상이 순회 수단의 이름이다).
# 즉 판정기 없이 돌면 이 래칫은 초록이 아니라 **58 > 57 로 빨개진다** — 조용히 통과하는
# 방향이 아니라는 것을 그 한 자리가 증명한다.
. "$(cd "$(dirname "$0")" && pwd)/lib/judge-bin.sh"
MASK_BIN="$(resolve_judge mask-source TASTY_MASK_SOURCE_BIN "$ROOT")"

SCAN_ROOT="$ROOT"
if [ -n "$MASK_BIN" ]; then
    MASKED="$(mktemp -d)"
    trap 'rm -rf "$MASKED"' EXIT
    if "$MASK_BIN" "$MASKED/det" "$ROOT" tests crates >/dev/null; then
        SCAN_ROOT="$MASKED/det"
    else
        echo "[shared-walk] 마스킹 실패 — 원문에서 센다(주석·문자열 안의 언급까지 세어진다)." >&2
    fi
else
    echo "[shared-walk] 원문에서 센다 — 주석·문자열 안의 언급까지 세어진다." >&2
fi

# 래칫 상한. **실제 건수와 같아야 한다** — 크면 그 차이만큼 조용히 받아준다.
#
# 2026-09-06 실측 57. 이 값의 계보: 같은 날 레포 전체의 `read_dir(` 는 131 이고, 그중
# 통합 테스트 타깃의 몫이 57 이다. 나머지 74 는 이 래칫의 대상이 아니다(런타임
# 파일시스템을 읽는 프로덕션 코드와 순회 도구 자신). 회차 전에는 59 였고 둘이 공용
# 순회로 옮겨 가면서 57 이 됐다 — 즉 이 수가 옳은 방향으로 움직이는 것이 관측됐다.
#
# ★ 그래서 지금 **여유가 0 이다**(건수 57 == 상한 57). 직접 순회를 하나라도 새로 들이는
#   변경은 그 자리에서 빨개진다. 그것이 이 게이트의 의도이고, 아래 실패문이 옮길 헬퍼를
#   이름으로 지목한다 — 상한을 올려 통과시키는 길은 없다. 여유가 0 이라는 사실 자체를
#   여기 적어 두는 이유는, 안 적으면 처음 걸린 사람이 그것을 결함으로 읽기 때문이다.
#   ★ 그리고 여유 0 이 이 게이트에서 **옳은** 이유는 따로 있다. 여유는 다른 게이트가
#   그 구간을 볼 때만 정당하다(`check-frozen-sum-ratchet.sh` 의 여유가 그 형태다 —
#   그 폭을 파일 크기 게이트가 본다). 직접 순회에는 그런 게이트가 없으므로 여기서
#   여유는 곧 아무도 안 보는 구간이 된다.
CAP=57

report=""
count=0

while IFS= read -r file; do
    [ -z "$file" ] && continue
    # 사본에 없는 파일은 **그 파일만** 원문에서 센다 — 건너뛰면 모수가 조용히 줄고,
    # 줄어든 모수는 언제나 초록이다.
    scan="$SCAN_ROOT/$file"
    [ -f "$scan" ] || scan="$file"
    # `|| true` 로 rc 만 삼킨다 — 없는 것과 못 센 것을 같은 0 으로 만들지 않으려면
    # 여기서 `|| echo 0` 을 쓰면 안 된다. 파일이 없으면 위에서 원문으로 떨어진다.
    hits=$({ grep -o 'read_dir(' "$scan" || true; } | wc -l)
    [ "$hits" -eq 0 ] && continue
    report+="  ${file}: ${hits}"$'\n'
    count=$((count + hits))
done <<<"$FILES"

echo "통합 테스트 타깃의 직접 read_dir( : ${count}건 (상한 ${CAP})"
echo

if [ "$count" -gt "$CAP" ]; then
    printf '%s' "$report"
    echo
    echo "직접 순회가 늘었다: ${count} > 상한 ${CAP}."
    if [ "$SCAN_ROOT" = "$ROOT" ]; then
        echo
        echo "★ 다만 이 값은 **판정기 없이 원문에서 센 값**이다(위 stderr 참조). 그러면 주석과"
        echo "  문자열 안의 언급까지 세어져 실측으로 +2 가 붙는다 — 그 +2 는 회귀의 크기가"
        echo "  아니라 **세는 사본이 바뀐 폭**이다. 회귀를 판정하기 전에 먼저 판정기를 지어라:"
        echo "      cargo build -p tasty-doc-guards --bin mask-source"
        echo "      target/debug/mask-source --check-fresh ."
        echo "  낡은 판정기도 없는 것으로 다뤄지므로 --check-fresh 가 rc=0 이어야 값이 유효하다."
        echo
    fi
    echo "새 순회를 tasty_doc_guards::floored_walk::walk_with_floor 로 옮겨라 — 거기서는"
    echo "하한이 인자라 빠뜨릴 수 없고, 실패문과 '하한을 내려서 통과시키지 마라' 는"
    echo "금지를 공용 함수가 만든다. 파일을 모으면 walk_with_floor, 디렉토리를 모으면"
    echo "walk_dirs_with_floor 다(뒤쪽은 하한이 모은 수가 아니라 훑은 수에 걸린다)."
    echo "상한을 올려서 통과시키지 마라 — 래칫은 한 방향으로만 돈다."
    exit 1
fi

if [ "$count" -lt "$CAP" ]; then
    echo "직접 순회가 줄었다: ${count} < 상한 ${CAP}."
    echo "이 스크립트의 CAP 을 ${count} 로 내려라. 상한이 실제보다 크면 그 차이만큼"
    echo "새 순회를 조용히 받아준다 — 남는 여유가 곧 안 보는 구간이다."
    exit 1
fi
