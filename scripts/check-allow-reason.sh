#!/usr/bin/env bash
# `#[allow(...)]` 계열 억제에 근거 주석(`reason:` / `이유:` / `complexity-exempt:` /
# `SAFETY`)이 같은 줄이나 **바로 위에 붙은 주석 블록**에 있는지 감사한다.
#
# ── 술어가 무엇을 세는가 (세 번 넓혔다) ──────────────────────────────────
# 1. **형태**: `#[allow(` 만 보면 `#[cfg_attr(<조건>, allow(...))]` 을 한 건도 못 본다.
#    조건부 억제는 **어떤 조합에서만** 린트를 끄는 형태라 오히려 사유가 더 필요하다 —
#    다른 조합에서 살아 있으니 안전해 보이는데, 그 조합에서 무엇이 꺼졌는지는 아무도
#    안 본다. 실측(2026-09-05): 그 형태가 60 자리였고 감사 밖이었다.
# 2. **마커**: 이 레포는 근거를 한글 `이유:` 로 적는다(실측 41 자리). 영문 마커만
#    보면 그 41 이 전부 "근거 없음" 으로 세어진다 — 세는 대상이 아니라 표기를 센다.
# 3. **창**: 근거는 보통 여러 줄짜리 주석 블록이라 직전 한 줄만 보면 블록의 마지막
#    줄만 보게 된다. 그래서 **붙어 있는 주석 블록 전체**를 본다. 창을 1→2→3→4→6→무한
#    으로 넓히며 잰 잔여는 279 → 244 → 236 → 234 → 232 → 231 로 6 부터 포화한다.
#    임의의 상수를 박는 대신 블록 경계(빈 줄·코드 줄)를 쓴다.
#
# ── 이 수는 상한인가 하한인가: **둘 다다. 극성이 하나가 아니다** ─────────
# 잔여는 한 술어의 산출이 아니라 **두 술어의 차**다(억제를 찾는 술어 − 근거를 찾는
# 술어). 그래서 덜 찾았을 때 값이 움직이는 방향이 술어마다 반대다. 위 세 번의 확장이
# 그 부호를 이미 재 놓았다:
#   억제를 더 찾자    → 값이 **올랐다** (조건부 억제 60 자리가 감사 안으로 들어왔다)
#   근거를 더 찾자    → 값이 **내렸다** (279 → 231)
# ⇒ 억제 술어가 덜 찾으면 이 수는 실제보다 **작고**(안 보는 자리가 생긴다),
#   근거 술어가 덜 찾으면 실제보다 **크다**(없는 결함을 신고한다).
#   한 방향만 적으면 반대쪽 확장이 값을 왜 움직였는지 설명되지 않는다.
#
# ── 왜 hard-fail 이 아니라 래칫인가 ──────────────────────────────────────
# 잔여가 0 이 아니라서 hard-fail 로 걸면 main 이 그 자리에서 빨개진다. 그렇다고
# 리포트로 두면 **건수와 무관하게 항상 통과**하는 칸이 하나 생긴다 — 채널은 도는데
# 술어가 아무것도 안 보는 상태이고, 초록이 뜨니 더 위험하다.
#
# 그래서 상한을 박은 **래칫**이다. 세 방향을 다 본다:
#   늘면        실패한다 — 오늘부터 새로 들어오는 것은 전부 빨갛다.
#   줄면        실패한다 — 상한을 같이 내리라는 뜻이다. 상한이 실제보다 크면 그
#               차이만큼 조용히 받아주므로, **여유는 곧 안 보는 구간**이다.
#   스캐너가 깨지면 실패한다 — `set -euo pipefail` 로 그 자리에서 죽는다.
#
# 상한은 줄어들 수만 있다. 늘리려면 이 수를 고쳐야 하고, 그 한 줄이 리뷰에 보인다.
#
# 채널: .github/workflows/script-gates.yml (main push · PR)
# 사용: scripts/check-allow-reason.sh

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# ── 좌변은 **한 값이다** — 지목처가 다섯이었다 ────────────────────────────
# 이 게이트는 같은 트리를 다섯 번 지목한다: rg 분기 · git 분기 · 미추적 검사 ·
# 마스킹 사본 둘(det · txt). 다섯이 따로 적혀 있으면 누가 하나를 손댈 때 나머지가
# 안 따라가고 **그 어긋남은 조용하다** — 형제 `check-intent-discipline.sh` 가 정확히
# 그 형태로 갈려 있었다(그쪽은 넷이었다). 여기는 표기까지 갈린다: git 은 pathspec,
# rg 와 마스커는 디렉토리를 받는다. 그래서 pathspec 하나만 두고 뿌리는 첫 세그먼트로
# **기계적으로 만든다.** 손으로 맞출 자리가 없어야 어긋날 자리도 없다.
# `tests/allow_reason_gate.rs` 가 이 값을 늘려 다섯이 전부 따라가는지를 종료 코드로
# 묻는다.
SCAN_SPECS=('crates/*.rs' 'src/*.rs')
SCAN_DIRS=()
for _spec in "${SCAN_SPECS[@]}"; do
    _root=${_spec%%/*}
    case " ${SCAN_DIRS[*]:-} " in *" $_root "*) ;; *) SCAN_DIRS+=("$_root") ;; esac
done

# `|| true` 로 rc 만 삼킨다 — `rg --files` 는 **매치가 0 이면 rc=1** 이라(실측), `set -e`
# 아래에서는 그 자리에서 조용히 죽는다. 그때 나가는 rc 는 위반과 **같은 1** 이고 출력은
# 한 줄도 없다. 아래 빈 좌변 검사가 그 갈래를 받아 말이 되는 문장으로 바꾼다.
#
# **어느 분기를 탔는지 값으로 남긴다.** 둘은 같은 것을 세지 않는다 — `rg --files` 는
# 미추적 `.rs` 를 세고 `git ls-files` 는 안 센다. 그래서 rg 가 있는 러너와 없는
# 작업 트리가 **같은 상한을 다른 모수에 대고 판정**할 수 있다. 어느 쪽을 쟀는지가
# 출력에 없으면 그 차이는 값이 흔들릴 때에야, 그것도 원인 미상으로 드러난다.
# 진단 스텝을 따로 두지 않는 이유는 이 줄이면 다음 push 의 로그가 답하기 때문이다.
if command -v rg >/dev/null 2>&1; then
    LEFT_SOURCE=rg
    FILES=$(rg --files -g '*.rs' "${SCAN_DIRS[@]}") || true
else
    LEFT_SOURCE=git-ls-files
    FILES=$(git ls-files -- "${SCAN_SPECS[@]}") || true
fi

# ── 안 본 것과 없는 것을 가른다 ────────────────────────────────────────────
# 좌변이 비면 잔여가 0 이 되고, 이 게이트는 양방향 래칫이라 `0 < CAP` 으로 죽기는 한다.
# **문제는 실패문이다** — 그 경로에서 나오는 문장은 "상한을 0 으로 내려라" 이고, 그대로
# 따르면 이 게이트는 영구히 눈이 먼다. 0 을 "찾았는데 없다" 로 대답하는 것이다.
#
# 이 검사는 좌변이 **완전히** 빈 경우만 잡는다. 반쯤 줄어든 좌변은 여기를 통과해 아래
# 상한 미달 분기로 가므로, 갈래 열거는 그쪽 실패문이 함께 진다.
#
# rc 를 위반(1)과 다르게 낸다. 측정이 안 된 것은 규율 위반이 아니라 환경·도구 문제이고,
# 둘을 같은 코드로 내면 CI 에서 "이 회차에 무엇을 했는가" 가 안 갈린다. 같은 근거로 같은
# 코드를 쓰는 자리가 이미 있다 — `scripts/check-file-size.sh` 의 측정 실패 exit 2.
if [ -z "$FILES" ]; then
    echo "검사 대상 .rs 를 하나도 못 찾았다 — 좌변이 깨졌다. 이 상태의 0 은 '근거 없는" >&2
    echo "억제가 없다' 가 아니라 '아무것도 안 봤다' 다. 상한을 내리지 마라." >&2
    exit 2
fi

# ── 아직 인덱스에 없는 `.rs` 가 있으면 판정하지 않는다 ──────────────────────
# `git ls-files` 분기의 모수는 인덱스이고 컴파일러의 모수는 디렉토리 실물이다. 미추적
# `.rs` 가 있는 동안 둘이 갈린다 — 그 파일은 빌드에 **들어가면서** 여기서는 안 세어진다.
# 그 창이 하필 새 소스를 짓는 동안이고, 다른 게이트(fmt·clippy)는 디렉토리를 보므로 같은
# 순간에 정상으로 답한다. 형제 `check-shared-walk-ratchet.sh` 에 이미 같은 검사가 있다.
#
# **rg 분기에는 이 창이 없다** — `rg --files` 가 미추적 `.rs` 도 낸다. 그래서 검사를 그쪽에
# 걸면 정상 상황을 판정 불가로 만든다. 창이 있는 분기에만 건다.
if [ "$LEFT_SOURCE" = git-ls-files ]; then
    UNTRACKED=$(git ls-files --others --exclude-standard -- "${SCAN_SPECS[@]}") || true
    if [ -n "$UNTRACKED" ]; then
        echo "인덱스에 없는 .rs 가 있다 — 이 상태에서는 판정하지 않는다." >&2
        echo "이 파일들은 빌드에 들어가지만 좌변(git ls-files)이 못 본다. 지금 세면 그 억제가" >&2
        echo "빠진 수가 나오고, 그 수가 상한보다 작으면 '줄었다' 로 읽혀 상한이 내려간다." >&2
        printf '%s\n' "$UNTRACKED" | sed 's/^/  /' >&2
        echo "git add 한 뒤 다시 돌려라." >&2
        exit 2
    fi
fi

# ── 문자열 리터럴을 덮은 사본에서 센다 ─────────────────────────────────────
#
# 이 검사는 텍스트 스캔이라 타입을 모르고, **문자열 안의 억제 형태를 실물로 센다.**
# 그 형태를 소스에 쓰는 것은 가드의 회귀 픽스처다 — 판정 대상 형태를 회귀로 박으려면
# 그 형태를 써야 하고, 쓴 순간 이 게이트의 모수가 된다(실측으로 여러 번 밟았다).
#
# 판정을 여기서 다시 구현하지 않는다. 러스트 층이 이미 그 판정을 갖고 있고
# (`tasty_doc_guards::source_text`), 셸이 자기 렉서를 만들면 같은 물음에 답이 둘이 된다.
# **주석은 남기는 마스크**를 쓴다 — 이 게이트는 억제의 유무만이 아니라 **사유 주석의
# 유무**를 함께 묻기 때문이다. 주석까지 덮으면 그 물음의 답이 사라진다.
#
# 줄 번호는 보존되므로 보고 좌표는 **원본 경로:줄** 그대로다.
#
# 판정기가 없거나 낡았으면 원문에서 센다 — 그쪽은 더 많이 세는 방향이라 조용한 통과를
# 안 만든다. 다만 래칫이라 **넘치면 실패한다**: 그래서 자동 채널이 판정기를 먼저 짓는다.
. "$(cd "$(dirname "$0")" && pwd)/lib/judge-bin.sh"
resolve_judge mask-source TASTY_MASK_SOURCE_BIN "$ROOT"
MASK_BIN="$JUDGE_BIN"

# **두 물음에 두 사본을 쓴다.** 억제가 *있는가* 는 코드에만 있어야 하므로 주석까지 덮은
# 사본에서 묻고, 사유 *주석*이 붙어 있는가 는 주석이 남은 사본에서 묻는다. 한 사본으로
# 둘을 다 하면 어느 쪽이든 틀린다 — 주석을 남기면 주석 안의 `#[allow(...)]` 언급이
# 억제로 세어지고(실측 1 자리), 주석을 덮으면 근거가 통째로 사라져 전부 위반이 된다.
# 줄 번호는 두 사본 모두 보존되므로 같은 i 로 맞물린다.
DET_ROOT="$ROOT"
TXT_ROOT="$ROOT"
if [ -n "$MASK_BIN" ]; then
    MASKED="$(mktemp -d)"
    trap 'rm -rf "$MASKED"' EXIT
    if "$MASK_BIN" "$MASKED/det" "$ROOT" "${SCAN_DIRS[@]}" >/dev/null \
        && "$MASK_BIN" --keep-comments "$MASKED/txt" "$ROOT" "${SCAN_DIRS[@]}" >/dev/null; then
        DET_ROOT="$MASKED/det"
        TXT_ROOT="$MASKED/txt"
    else
        echo "[allow-reason] 마스킹 실패 — 원문에서 센다(문자열·주석 안의 억제 형태까지 세어진다)." >&2
    fi
else
    echo "[allow-reason] 원문에서 센다 — 문자열·주석 안의 억제 형태까지 세어진다." >&2
fi

REASON_PATTERN='reason:|이유:|complexity-exempt:|SAFETY'

# 래칫 상한. **실제 건수와 같아야 한다** — 크면 그 차이만큼 조용히 받아준다.
# 줄였으면 이 수도 같이 내려라(스크립트가 그 자리에서 시킨다).
#
# 이 수는 술어를 넓힌 회차에 다시 잰 값이다(234 → 231). **위반이 줄어서가 아니다** —
# 세는 형태가 60 자리 늘고(조건부 억제) 인정하는 표기가 41 자리 늘어(한글 마커·블록 창)
# 두 변화가 상쇄된 값이다. 그래서 이 231 은 이전 234 와 **같은 것을 센 수가 아니다.**
#
# 184 → 183 → 182 도 같은 성질이다. 위반이 줄어서가 아니라 **언급을 실물로 세던 자리**가
# 마스킹으로 빠진 것이다: 184 → 183 은 문자열 안의 억제(생성 코드를 조립하는 자리),
# 183 → 182 는 **주석 안의 억제 언급** 한 자리다(실측으로 그 한 줄을 고쳐 확인했다).
# 판정기가 없어 원문에서 세면 이 값이 184 로 돌아와 래칫이 실패한다 — 자동 채널이
# 판정기를 먼저 짓는 이유다.
CAP=182

report=""
count=0

while IFS= read -r file; do
    [ -z "$file" ] && continue
    # 사본에 없는 파일(마스커와 rg 의 파일 집합이 완전히 같지는 않다)은 **그 파일만**
    # 원문에서 센다 — 건너뛰면 모수가 조용히 줄고, 줄어든 모수는 언제나 초록이다.
    det="$DET_ROOT/$file"
    [ -f "$det" ] || det="$file"
    txt="$TXT_ROOT/$file"
    [ -f "$txt" ] || txt="$file"
    hits=$(awk -v reason_pat="$REASON_PATTERN" '
        # 첫 파일 = 탐지용(주석까지 덮은 사본), 둘째 = 근거용(주석이 남은 사본).
        FNR == NR { det[FNR] = $0; ndet = FNR; next }
        { txt[FNR] = $0 }
        END {
            for (i = 1; i <= ndet; i++) {
                line = det[i]
                # 무조건 억제와 조건부 억제(`cfg_attr(..., allow(...))`)를 함께 센다.
                if (line !~ /#!?\[allow\(/ && !(line ~ /#!?\[cfg_attr\(/ && line ~ /allow\(/)) {
                    continue
                }
                found = (txt[i] ~ reason_pat)
                # 바로 위에 붙은 주석 블록 전체를 본다 — 빈 줄이나 코드 줄에서 끊긴다.
                for (k = i - 1; k >= 1 && !found; k--) {
                    if (txt[k] !~ /^[[:space:]]*\/\//) break
                    if (txt[k] ~ reason_pat) found = 1
                }
                if (!found) printf "%d: %s\n", i, txt[i]
            }
        }
    ' "$det" "$txt")
    [ -z "$hits" ] && continue
    while IFS= read -r hit; do
        report+="${file}:${hit}"$'\n'
        count=$((count + 1))
    done <<<"$hits"
done <<<"$FILES"

# 훑은 수를 함께 찍는다 — 상한 래칫은 적중 수만 지키고 좌변 크기는 안 본다. 좌변이
# 반쯤 줄어도(적중 0 인 파일이 빠져도) 이 수 없이는 화면에 아무 신호가 없다.
scanned_count=$(printf '%s\n' "$FILES" | wc -l)

echo "훑은 .rs ${scanned_count}개 (좌변=${LEFT_SOURCE})."
echo "근거 없는 #[allow(...)] : ${count}건 (상한 ${CAP})"
echo

# ── 판정기 없이 센 값으로는 래칫을 판정하지 않는다 ────────────────────────────
# 위 폴백은 **더 많이 세는** 방향이라 조용한 통과는 안 만든다. 그런데 래칫은 양방향이라
# "조용한 통과가 없다" 로 끝나지 않는다 — 값이 상한을 넘으면 실패문이 "상한을 올려서
# 통과시키지 마라" 로 나가고, 그것은 **실재하지 않는 회귀에 대한 처방**이다. 그 처방을
# 따르면 래칫이 영구히 헐거워지고, 되돌릴 사람은 이유를 모른다.
#
